const List<String> languageRoles = ['native', 'target', 'both'];

/// Готовность языка. `launched` требует полноты, `draft` — нет.
const List<String> languageStatuses = ['draft', 'launched'];

/// Сколько звёзд должно быть у созвездия на ярусе, чтобы оно вообще
/// появилось на карте.
///
/// Считается по фразам: звезда — это фраза. Раньше здесь стоял `starsPerTier`
/// — фиксированные 12/24/48/72/96 накопительно, и валидатор требовал их
/// точного совпадения. Порог вместо равенства: тема просто ждёт того яруса,
/// на котором ей есть что показать.
const int minStarsForConstellation = 8;

/// Пометки под центром круга. Сегодня это регистр фразы.
///
/// Закрытый набор кодов, а не свободный текст: `register: casual` уезжал на
/// экран как есть, и под каждой из 432 фраз стояло английское служебное
/// слово. Строку к коду даёт локализация — на языке интерфейса.
///
/// Словарные пометки (часть речи, исчисляемость, число) ушли вместе со
/// словарным слоем: у фразы части речи нет.
///
/// Дублируется с `lib/domain/entities/prompt_tag.dart`, совпадение проверяет
/// тест.
const Set<String> promptTags = {'casual', 'formal'};

/// Чем фраза является. Закрытый набор, колонка `phrases.kind` (v7).
///
/// * `phrase` — готовая реплика: её произносят как есть;
/// * `example` — законченный образец речевой модели. Пришёл на место шаблона
///   с многоточием: «Ich heiße Alex.» вместо «Ich heiße ...». Игрок повторяет
///   не имя Alex, а модель;
/// * `idiom` — устойчивое выражение, у которого перевод **смысловой**.
///
/// Набор закрыт по той же причине, что и [promptTags]: свободный текст в этом
/// поле означал бы строку, которую нечем показать и не с чем сверить. Но
/// показывается он иначе — сегодня не показывается вовсе: `kind` нужен
/// проверкам контента, а не экрану. Ближайшая такая проверка — сверка
/// перевода с буквальным смыслом: она обязана пропускать `idiom`, иначе
/// объявит дефектом единственно верный перевод идиомы.
///
/// Соответствие колонке «Тип» листа-источника: «Фраза» → `phrase`, «Пример» →
/// `example`, «Идиома» → `idiom`. Перевод русских пометок в коды делает
/// `tool/import_phrasebook.dart`.
const Set<String> phraseKinds = {'phrase', 'example', 'idiom'};

/// Чем фраза считается, если `kind:` в файле не написан.
///
/// Умолчание есть, и это не мягкость к небрежным файлам. `phrase` — обычный
/// случай (1231 строка корпуса из 1500), а `example` и `idiom` — заявления о
/// строке, которые автор делает осознанно. Требуй поле от каждой фразы — и
/// добавление одной строки руками стало бы правкой из двух полей, второе из
/// которых почти всегда одно и то же.
///
/// Обратная сторона названа честно: опечатка в самом слове (`idiome`) молчанием
/// не станет — набор закрыт, и валидатор говорит об этом ошибкой. А вот
/// **забытая** пометка у идиомы невидима: она читается как обычная фраза.
/// Поймать такое можно только вычиткой темы `idioms_speech`.
const String defaultPhraseKind = 'phrase';
