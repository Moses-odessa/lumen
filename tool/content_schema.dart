/// Схема `content.db` в одном месте: её читают и `build_content.dart`, и
/// `validate_content.dart`.
///
/// Имена таблиц и колонок обязаны совпадать с тем, что генерирует Drift для
/// `lib/data/content/content_database.dart` — иначе приложение откроет базу и
/// упадёт на первом запросе. Версия схемы пишется в `PRAGMA user_version` и
/// сверяется с `ContentDatabase.schemaVersion`.
library;

/// Версия схемы контента. Меняется вместе с `ContentDatabase.schemaVersion`.
///
/// v2 убрала `audio_id`: озвучка перешла на синтез устройства и произносит
/// текст, а не заранее записанный файл.
///
/// v3 сделала две вещи. Во-первых, у фразы стало несколько пропусков:
/// `phrases.answer` уехал в `phrase_slots`, рядом встали `phrase_options`
/// (неверные слова по слоту) и `phrase_translations` (перевод фразы целиком).
/// Во-вторых, появилась таблица `languages`: язык объявляет о себе сам, а не
/// перечисляется списком в коде.
///
/// v4 сменила устройство фразовой механики. Пропусков стало от двух до всех
/// слов, а вокруг — ровно вынутые слова, без посторонних. `phrase_options`
/// уехала целиком, а вместо неё встала `phrase_orders` — сборки, которые
/// принимаются верными.
///
/// **v5 — разговорник.** Единицей изучения стала фраза, а отдельного слова в
/// игре больше нет. Вместе со словом ушли пять таблиц:
///
/// * `concepts` и `lexemes` — единицей была словарная запись; теперь фраза
///   сама себе запись: у неё есть ярус, созвездие и перевод;
/// * `distractors` — неверные варианты больше не пишутся руками. Вокруг
///   фразы лежат **другие фразы, которые игрок уже знает**: новое даётся
///   методом исключения, а знакомое проверяется тем же кругом;
/// * `phrase_slots` и `phrase_orders` — вставки слов в предложение больше
///   нет, значит нет ни пропусков, ни списка верных сборок;
/// * `phrase_concepts` — связывать фразу со словом больше незачем.
///
/// `phrases.template` стал `phrases.text`: шаблон с пропуском нужен был
/// механике вставки. Сборка подставляет ответ в шаблон и пишет готовое
/// предложение — в игре у фразы нет ни пропусков, ни скрытых частей.
///
/// `phrases.idx` — порядок внутри созвездия и яруса, как он написан в файле.
/// Прежнюю последовательность знакомства задавала частотность слова
/// (`concepts.freq_rank`), а у фразы частотности нет: порядок решает автор.
///
/// **v6 добавила `constellation_names`.** До неё у созвездия было только
/// имя-slug (`first_contact`), и карта подписывала темы латиницей. Имя темы —
/// **контент**, а не строка интерфейса: тема приходит вместе с фразами и
/// обязана добавляться тем же одним файлом. В ARB ей вдобавок нет места
/// технически — `gen-l10n` не умеет достать строку по вычисляемому ключу, и
/// пятьдесят тем превратились бы в `switch` на пятьдесят ветвей, который
/// забудут дополнить на пятьдесят первой.
///
/// **v7 добавила `phrases.kind`** — чем фраза является: готовой репликой
/// (`phrase`), образцом речевой модели (`example`) или идиомой (`idiom`).
/// Различие пришло с корпусом 1500 (лист объявляет его колонкой «Тип»), и до
/// v7 оно жило только в голове автора листа.
///
/// Колонка нужна из-за перевода. У идиомы он **смысловой, а не буквальный**:
/// «Ich habe den Faden verloren.» → «Я потерял нить мысли.», и всякая будущая
/// проверка перевода на буквальность обязана идиомы пропускать — иначе она
/// объявит дефектом ровно то, что в идиоме и есть правильно. Тридцать таких
/// фраз лежат в `idioms_speech`, и отличить их от остальных по тексту нечем.
/// У `example` смысл другой: это законченный образец модели, пришедший на
/// место шаблона с многоточием («Ich heiße Alex.» вместо «Ich heiße ...»), —
/// то есть строка, которую игрок повторяет не дословно, а по образцу.
const int contentSchemaVersion = 7;

/// DDL контентной базы. Индексы — под запросы рантайма: выборка фраз
/// созвездия по ярусу и набор калибровки.
const List<String> contentSchemaDdl = [
  // Языки базы: код, роль, готовность, самоназвание и покрытие.
  //
  // Покрытие считается при сборке, а не объявляется в файле: объявленное
  // число разошлось бы с содержимым при первой же правке — этот проект уже
  // ловил такое на строке о вычитке в launch.yaml.
  '''
  CREATE TABLE languages (
    code TEXT NOT NULL PRIMARY KEY,
    role TEXT NOT NULL,
    status TEXT NOT NULL,
    name TEXT NOT NULL,
    phrases INTEGER NOT NULL
  )
  ''',
  // Фраза — единица изучения. `text` готов к показу: подстановка сделана
  // сборкой, скрытых частей у фразы нет.
  //
  // `kind` не NULL, в отличие от соседнего `register`, и разница не в
  // аккуратности. Пометка регистра — свойство, которое у фразы либо есть, либо
  // нет: 1315 строк корпуса нейтральны, и NULL там правдив. А чем-то фраза
  // является всегда, поэтому у неё есть значение по умолчанию
  // ([defaultPhraseKind]), а не пустота: NULL пришлось бы читать «неизвестно
  // чем», и всякий, кто спрашивает «это идиома?», получал бы третий ответ,
  // которого в закрытом наборе нет.
  '''
  CREATE TABLE phrases (
    id TEXT NOT NULL PRIMARY KEY,
    lang TEXT NOT NULL,
    tier TEXT NOT NULL,
    constellation TEXT NOT NULL,
    idx INTEGER NOT NULL,
    text TEXT NOT NULL,
    kind TEXT NOT NULL,
    register TEXT NULL
  )
  ''',
  // Перевод фразы на родной язык. Живёт в языковом файле, а не рядом с
  // фразой: язык добавляется одним файлом.
  '''
  CREATE TABLE phrase_translations (
    phrase_id TEXT NOT NULL,
    lang TEXT NOT NULL,
    text TEXT NOT NULL,
    PRIMARY KEY (phrase_id, lang)
  )
  ''',
  // Имя созвездия на одном языке. Один ряд — одно имя.
  //
  // Язык изучения лежит здесь наравне с языками подсказок, и «перевода» имени
  // в таблице нет: у изучаемого языка есть текст — ровно так же, как с самой
  // фразой. Приходят они при этом из разных мест (шапка файла фраз против
  // раздела `constellations:` языкового файла), и это разница исходников, а не
  // разница строк в базе.
  //
  // Индекса по одному `lang` тут нет намеренно, хотя рантайм спрашивает
  // именно так (`constellationNamesFor`), а у соседних `phrase_translations`
  // такой индекс стоит. Разница в размере: переводов тысяча на язык, а имён —
  // пятьдесят тем на пять языков, то есть двести пятьдесят коротких рядов,
  // читаемых один раз за открытие карты. Решение записано и в
  // `lib/data/content/content_database.dart`; расходиться им нельзя.
  '''
  CREATE TABLE constellation_names (
    constellation TEXT NOT NULL,
    lang TEXT NOT NULL,
    name TEXT NOT NULL,
    PRIMARY KEY (constellation, lang)
  )
  ''',
  '''
  CREATE TABLE calibration_items (
    id TEXT NOT NULL PRIMARY KEY,
    tier TEXT NOT NULL,
    phrase_id TEXT NOT NULL,
    kind TEXT NOT NULL
  )
  ''',
  '''
  CREATE TABLE content_meta (
    key TEXT NOT NULL PRIMARY KEY,
    value TEXT NOT NULL
  )
  ''',
  'CREATE INDEX phrases_constellation_tier ON phrases (constellation, tier)',
  'CREATE INDEX phrase_translations_lang ON phrase_translations (lang)',
  'CREATE INDEX calibration_tier ON calibration_items (tier)',
];

/// Ярусы в порядке возрастания. Дублируется с `domain/entities/tier.dart`
/// намеренно: `tool/` — отдельная программа и не тянет за собой `lib/`.
const List<String> tiers = ['a0', 'a1', 'a2', 'b1', 'b2'];

/// Поле имени созвездия в шапке файла фраз: `name:` рядом с `constellation:`.
///
/// Константа, а не строка по месту, из-за совпадения написания. `name:` в
/// языковом файле — это самоназвание языка («Deutsch»), а `name:` в файле фраз
/// — имя темы («Erster Kontakt»); два разных поля с одним написанием в двух
/// видах файлов. Кто прочитает одно вместо другого, получит осмысленную
/// строку, а не ошибку разбора, — то есть ошибку молча. Имя константы
/// говорит, о каком из двух полей речь, и едет вместе с ним в три файла:
/// пишет его импорт, читает `content_sources.dart`, называет в сообщении
/// валидатор.
const String constellationNameField = 'name';

/// Раздел имён созвездий в языковом файле: `constellations:` рядом с
/// `phrases:`.
///
/// Совпадает по написанию с полем `constellations:` записи о вычитке в
/// `launch.yaml` — там это список прочитанных тем, здесь карта «slug → имя».
/// Причина держать константу та же, что и у [constellationNameField].
const String constellationNamesSection = 'constellations';

