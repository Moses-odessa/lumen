import 'package:flutter_test/flutter_test.dart';
import 'package:lumen/domain/entities/circle_question.dart';
import 'package:lumen/domain/entities/game_mode.dart';
import 'package:lumen/domain/entities/tier.dart';

/// Вопрос круга: шесть фраз вокруг центра, верная одна.
///
/// Проверяется только то, из-за чего вопрос — отдельный тип: что считается
/// верным, каким текстом ответ уезжает в озвучку и подсветку и чем повтор
/// промаха отличается от самого промаха. Откуда взялись фразы вокруг и на
/// каком они языке — забота `QuestionBuilder` и `SessionLoader`, и
/// проверяется у них.
///
/// ── Что здесь было и почему больше нет ──────────────────────────────────
///
/// 1. Группа «несколько слотов», семь тестов про пропуски в предложении: у
///    каждого слота свой верный вариант, верное слово в чужом пропуске —
///    ошибка, слот вне шаблона не считается верным, заполненные пропуски
///    дают фразу целиком, скелет из одних пропусков, список равно верных
///    порядков слов. Вставки слов в предложение больше нет: единица изучения
///    — фраза целиком, и вопрос у неё один, «какая из шести». Вместе с
///    механикой из вопроса ушли `answers`, `slotCount`, `isSingleSlot`,
///    `answerFor`, `isCorrectFor`, `assembled`, `acceptsSlots`,
///    `acceptsAssembly` и `accepted` — охранять больше нечего.
///
///    Одно правило из этой группы перенесено, а не удалено:
///    «одинаковые плитки взаимозаменяемы». Плиток нет, совпадение текстов
///    осталось — ниже оно проверяется на вариантах круга.
///
/// 2. Тест «круг с одним вариантом — законный вопрос» удалён вместе с
///    `ScoreBalance.optionsMin`: вариантов всегда шесть
///    (`optionsPerCircle`). Знакомство перестало быть показом и стало
///    исключением — вокруг новой фразы стоят пять уже известных, — так что
///    круг из одного варианта теперь не законный вопрос, а сломанный:
///    исключать не из чего. Сборщик его и не отдаёт: меньше пяти известных
///    фраз — `QuestionBuilder.build` возвращает `null`, и это проверено у
///    сборщика.
///
/// 3. Тест «у всех механик выбора ответ занимает ровно один слот» удалён:
///    слот был один из двух способов ответить, а стал единственным. У
///    вопроса больше нет ни поля, ни ветки, которая зависела бы от механики,
///    — утверждение стало истинным по построению, а такой тест нельзя
///    сломать.
///
/// 4. Группа «ввод текста» (`isCorrectInput`: точный ответ, любой регистр,
///    опечатка в одну букву прощается, в коротком слове — нет) и тест про
///    `isTyped` удалены вместе с механикой «Набор». Поля ввода в игре нет
///    нигде, а терпимость к опечатке была нужна ровно затем, чтобы игра
///    проверяла знание, а не меткость на телефонной клавиатуре. Написание
///    после этого не тренируется ничем, и это осознанный размен:
///    возвращать эти тесты имеет смысл только вместе с полем ввода.
void main() {
  // Настоящий контент: шесть фраз яруса A0 из созвездий «Тело, здоровье и
  // помощь» и «Город». В тесте стоят предложения, а не слова, потому что
  // круг теперь устроен так: вокруг центра лежат пять фраз, которые игрок
  // уже знает, и шестая новая.
  const phrases = [
    'Ich muss zum Arzt, mein Kopf tut weh.',
    'Ich habe seit gestern Schmerzen im Rücken.',
    'Ich brauche Hilfe, das kann ich nicht allein.',
    'Ich habe einen Termin beim Arzt.',
    'Auf dem Stadtplan finde ich jede Straße.',
    'Ich bringe den Brief zur Post.',
  ];

  CircleQuestion question({
    GameMode mode = GameMode.pickTarget,
    String prompt = 'Мені потрібно до лікаря, у мене болить голова.',
    List<String>? options,
    int answerIndex = 0,
    bool isNew = false,
  }) =>
      CircleQuestion(
        itemId: 'doctor_a0_doctor',
        tier: Tier.a0,
        mode: mode,
        prompt: prompt,
        options: options ?? phrases,
        answerIndex: answerIndex,
        lumens: 50,
        isNew: isNew,
      );

  group('выбор варианта', () {
    test('верен один вариант, и он же отдаётся текстом', () {
      // `answer` — не удобство, а то, что после ответа произносится и
      // подсвечивается. Разъедься он с `answerIndex` — игрок услышал бы одну
      // фразу, а зачлась бы другая, и понять по экрану это невозможно.
      final q = question(answerIndex: 2);
      expect(q.isCorrectOption(2), isTrue);
      expect(q.isCorrectOption(0), isFalse);
      expect(q.isCorrectOption(5), isFalse);
      expect(q.answer, phrases[2]);
    });

    test('индекс вне круга не верен и текста не даёт', () {
      // Круг рисуется по `options`, так что таких индексов игрок нажать не
      // может — они приходят от сломанного сборщика. Забег в этот момент уже
      // идёт, и падение с RangeError стоило бы игроку всей серии, поэтому
      // здесь молчание, а не исключение.
      final q = question();
      expect(q.isCorrectOption(-1), isFalse);
      expect(q.isCorrectOption(6), isFalse);
      expect(question(answerIndex: 6).answer, isEmpty);
      expect(question(answerIndex: -1).answer, isEmpty);
    });

    test('две одинаковые фразы в круге зачитываются обе', () {
      // Столкновение переводов: у двух разных немецких фраз родной перевод
      // может совпасть буква в букву, и в `pickNative`/`listenNative`
      // вариантами стоят как раз переводы. Игрок видит две неотличимые
      // строчки; за каждой свой номер; верным сборщик пометил одну.
      //
      // Сравнивать только номер значит сказать «неверно» на строчке, которая
      // читается точно как правильная. Это то же правило, что охранял
      // удалённый тест «одинаковые плитки взаимозаменяемы, а номера — нет»:
      // плиток не стало, а совпадение текстов осталось.
      final q = question(
        // В центре фраза на изучаемом, вокруг — переводы: столкнуться могут
        // только они.
        mode: GameMode.pickNative,
        prompt: 'Gehen Sie nach rechts.',
        options: const [
          'Ідіть праворуч.',
          'У мене запис до лікаря.',
          'Ідіть праворуч.',
          'Я несу лист на пошту.',
          'На мапі я знаходжу кожну вулицю.',
          'Мені потрібна допомога, сам я цього не зроблю.',
        ],
        answerIndex: 0,
      );

      expect(q.isCorrectOption(0), isTrue);
      expect(q.isCorrectOption(2), isTrue, reason: 'близнец объявлен неверным');
      expect(q.isCorrectOption(1), isFalse);
    });
  });

  group('повтор круга', () {
    test('повтор промаха — другой объект с теми же полями', () {
      // Забег возвращает промах в конец очереди, и когда промах был
      // последним кругом, следующим показывается он же. Арена сбрасывает
      // выбор по смене **объекта** — сравнения по значению у вопроса нет и не
      // надо, два круга по одной фразе это два разных круга. Вернуть `this`
      // значит: арена не сбросилась, выбранный вариант на месте, ответов она
      // больше не принимает — забег ждёт вечно.
      //
      // Поля перечислены поштучно нарочно: новое поле, забытое в `again()`,
      // потеряется ровно на повторе — то есть там, где игрок уже ошибся, — и
      // это тот случай, который заметить труднее всего.
      const q = CircleQuestion(
        itemId: 'city_a0_right',
        tier: Tier.a1,
        mode: GameMode.listenNative,
        prompt: '',
        options: ['Ідіть праворуч.', 'Я несу лист на пошту.'],
        answerIndex: 0,
        lumens: 40,
        isNew: true,
        promptSpeech: 'Gehen Sie nach rechts.',
        answerSpeech: 'Gehen Sie nach rechts.',
        promptTag: 'formal',
        translation: 'Ідіть праворуч.',
      );

      final again = q.again();

      expect(again, isNot(same(q)), reason: 'арена не увидит нового круга');
      expect(again.itemId, q.itemId);
      expect(again.tier, q.tier);
      expect(again.mode, q.mode);
      expect(again.prompt, q.prompt);
      expect(again.options, q.options);
      expect(again.answerIndex, q.answerIndex);
      expect(again.lumens, q.lumens);
      expect(again.isNew, q.isNew);
      expect(again.promptSpeech, q.promptSpeech);
      expect(again.answerSpeech, q.answerSpeech);
      expect(again.promptTag, q.promptTag);
      expect(again.translation, q.translation);
    });

    test('окно ответа выключено только у знакомства', () {
      // `isNew` — единственное, чем круг говорит арене и забегу «не торопи».
      // Значение по умолчанию поэтому важнее, чем выглядит: перевернись оно,
      // и пять секунд исчезли бы из всей игры сразу — ни полосы, ни
      // просрочки, ни «не вспомнил». Заметить это по экрану нельзя, круг
      // выглядит как обычно.
      expect(question().isNew, isFalse);
      expect(question(isNew: true).again().isNew, isTrue,
          reason: 'повтор знакомства обязан снова остаться без окна');
    });
  });
}
