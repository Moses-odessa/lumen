/// Оценка одного ответа в терминах FSRS.
///
/// Ключевое отличие Lumen от обычной карточной программы: игрок **никогда не
/// оценивает себя сам**. Кнопок «легко / трудно» нет, потому что каждая такая
/// кнопка — это остановка в середине забега и повод соврать себе. Оценка
/// выводится из того, что игра и так измеряет: попал или нет и за сколько.
enum ReviewGrade {
  /// Не вспомнил. Слово теряет яркость и возвращается в конец забега.
  again(1),

  /// Вспомнил, но медленно — то, что нужно тренировать.
  hard(2),

  /// Обычное уверенное узнавание.
  good(3),

  /// Автоматизм: ответ пришёл раньше, чем игрок успел подумать.
  easy(4);

  const ReviewGrade(this.value);

  /// Числовое значение 1..4 — в этом виде оценка уходит в FSRS и в журнал.
  final int value;

  bool get isForgotten => this == ReviewGrade.again;

  static ReviewGrade fromValue(int value) => switch (value) {
        1 => ReviewGrade.again,
        2 => ReviewGrade.hard,
        4 => ReviewGrade.easy,
        _ => ReviewGrade.good,
      };
}
