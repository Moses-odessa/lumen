/// Пометки под центром круга: сегодня это регистр фразы.
///
/// Закрытый набор кодов, а не свободный текст, и это исправление конкретной
/// ошибки. Пометка `note` у лексемы писалась на языке своего файла: у
/// немецкого — по-русски. Немецкий здесь язык **изучения**, то есть его файл
/// читает не игрок, а автор контента, — и правильного языка у такой пометки
/// нет вообще. Украинскому игроку показывалось «неисчисляемое», англоязычному
/// тоже.
///
/// Регистр фразы был хуже: `register: casual` уезжал на экран как есть, и под
/// каждой из 432 фраз стояло английское служебное слово. Ни один язык, ни один
/// перевод — просто внутренний код, показанный человеку.
///
/// Поэтому пометка теперь код, а строку к нему даёт локализация — на языке
/// интерфейса, который игрок себе выбрал. Свободного текста в пометках больше
/// нет вовсе: он жил у лексем родного языка, а лексем не осталось.
///
/// Набор дублируется в `tool/content_schema.dart`: `tool/` — отдельная
/// программа и не тянет за собой `lib/`. Совпадение проверяется тестом.
/// Словарные пометки — часть речи, исчисляемость, число — ушли вместе со
/// словарным слоем: у фразы части речи нет. Осталось то, что у фразы есть.
const Set<String> promptTags = {'casual', 'formal'};

bool isPromptTag(String value) => promptTags.contains(value);
