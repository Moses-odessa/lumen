/// Четыре механики поверх одной геометрии — и пять кодов.
///
/// Экран всегда устроен одинаково: центр, вокруг варианты, соединение
/// пальцем. Меняется то, что в центре, на каком языке варианты и сколько их.
///
/// Множители и диапазоны яркости — в `domain/scoring/balance.dart`, здесь
/// только идентичность механики.
///
/// **Что было до этого набора и чего это стоило.** Прежних режимов было
/// шесть: узнавание, круг, тесный круг, слух, набор, фраза. Разница с новым
/// набором не в числе:
///
/// * «Круг» и «Тесный круг» отличались только видом дистракторов —
///   тематические против созвучных. Это параметр сложности, а не отдельная
///   механика, и держать его режимом значило, что этап уровня не может
///   попросить «то же, но с созвучными»: ему пришлось бы менять режим.
/// * «Слух» был один, потом стал двумя: понять, что сказали (варианты на
///   родном), и различить похожее (варианты на изучаемом). Второй вариант
///   удалён — см. [listenNative]. Вопрос на слух в игре один.
/// * «Набор» — поле ввода — удалён. Вместе с ним ушла экранная клавиатура,
///   правило «опечатка в одну букву засчитывается» и **единственная механика,
///   где форму нужно было произвести, а не выбрать**. Из оставшихся ближе
///   всего фраза при максимуме пропусков ([buildPhrase]): порядок слов
///   приходится восстанавливать по памяти. Написание после этого не
///   тренируется ничем, и это осознанный размен — набор на телефоне на чужом
///   языке самое раздражающее место игры.
enum GameMode {
  /// **a.** В центре слово или фраза на изучаемом языке, вокруг 1–6 вариантов
  /// на родном. Проверяет понимание.
  pickNative,

  /// **b.** В центре слово или фраза на родном языке, вокруг 1–6 вариантов на
  /// изучаемом. Проверяет воспроизведение.
  ///
  /// Вид дистракторов — параметр круга, а не механики: тематические на
  /// закреплении, созвучные на проверке.
  pickTarget,

  /// **c.** Слово звучит само, как только круг открылся; нажатие на динамик
  /// проигрывает заново. Вокруг 1–6 вариантов **на родном**. Проверяет
  /// восприятие на слух вместе со смыслом.
  ///
  /// Вариантов на изучаемом языке у вопроса на слух нет, и это единственный
  /// возможный ответ на вопрос «что мы тут тренируем». Такая механика была —
  /// `listenTarget`, «различить похожее на слух», — и она проверяла слух
  /// отдельно от смысла: игрок выбирал ту немецкую строчку, которая похоже
  /// звучит, ничего не понимая. Различать `Bahn` и `Bahnhof` полезно ровно
  /// тогда, когда знаешь, что это разные вещи; иначе это тренировка уха, а не
  /// языка. Созвучные дистракторы от этого не остались без работы: их
  /// спрашивает [pickTarget] на этапе проверки, где ответ надо произвести.
  listenNative,

  /// **e.** Фраза на изучаемом языке с пропусками, вокруг — вынутые из неё
  /// слова. Когда все пропуски заполнены, фраза проигрывается целиком и под
  /// ней проявляется перевод.
  ///
  /// Пропусков от двух до всех: это шкала сложности, а не набор механик.
  fillGaps,

  /// **e при максимуме пропусков**: пропущены все слова, то есть предложение
  /// собирается с нуля. Отдельный код, а не отдельная механика: сборка та же,
  /// но требует восстановить порядок слов по памяти — и стоит дороже.
  buildPhrase;

  /// Код механики в `Reviews.mode`.
  String get code => name;

  /// Механика производит слово или предложение, а не только узнаёт его.
  /// Отсюда растёт правило «горящего слова»: оно считается только здесь.
  ///
  /// Непроизводящих механик **две**, а не одна: понимание проверяется и с
  /// текста ([pickNative]), и со слуха ([listenNative]).
  bool get isProductive => switch (this) {
        GameMode.pickNative || GameMode.listenNative => false,
        GameMode.pickTarget || GameMode.fillGaps || GameMode.buildPhrase =>
          true,
      };

  /// В центре звук, а не текст. Без голоса в системе такую механику
  /// планировать нельзя: круг без звука — это круг без задания.
  bool get needsAudio => this == GameMode.listenNative;

  /// Варианты на языке изучения. Иначе — на родном.
  ///
  /// У вопроса на слух они всегда на родном: см. [listenNative].
  bool get optionsInTargetLanguage => switch (this) {
        GameMode.pickNative || GameMode.listenNative => false,
        GameMode.pickTarget || GameMode.fillGaps || GameMode.buildPhrase =>
          true,
      };

  /// Механика работает с целой фразой, а не с одним словом.
  bool get isPhrase =>
      this == GameMode.fillGaps || this == GameMode.buildPhrase;

  /// Механика, которую планировщик выбирает по яркости слова. Фразовые
  /// ставятся явно: у них другой источник материала.
  bool get isWordMode => !isPhrase;

  static GameMode fromCode(String code) {
    for (final m in values) {
      if (m.name == code) return m;
    }
    // Неизвестный код бывает у строк, записанных прежним набором режимов
    // («circle», «typing», «listenTarget»). Ничего в приложении их не читает,
    // но если прочитает — самая нейтральная механика та, в которую играют
    // больше всего.
    return GameMode.pickTarget;
  }
}

/// Вид дистракторов вокруг ответа.
///
/// Был разницей между двумя режимами, стал параметром круга. Этап уровня
/// теперь может попросить «то же самое, но с созвучными», не меняя механику.
enum DistractorKind {
  /// Та же тема, другое значение. Проверяет знание значения.
  far,

  /// Созвучные и однокоренные. Проверяет точность.
  near;

  /// Код в `content.db`, колонка `distractors.kind`.
  String get code => name;
}
