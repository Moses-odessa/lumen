/// Три механики поверх одной геометрии.
///
/// Экран всегда устроен одинаково: центр, вокруг шесть вариантов, соединение
/// пальцем. Меняется то, что в центре и на каком языке варианты.
///
/// **Единица изучения — фраза**, а не слово: игра стала разговорником.
/// Поэтому варианты вокруг — это другие фразы, и берутся они из тех, что
/// игрок уже знает.
///
/// **Что было до этого набора и чего это стоило.** Механик было шесть, потом
/// четыре, стало три.
///
/// * «Круг» и «Тесный круг» отличались только видом дистракторов —
///   тематические против созвучных. Это параметр сложности, а не отдельная
///   механика. Сегодня вида дистракторов нет вовсе: вокруг лежат известные
///   игроку фразы, и «неверный вариант» больше не пишется руками.
/// * «Слух» был один, потом стал двумя: понять, что сказали (варианты на
///   родном), и различить похожее (варианты на изучаемом). Второй удалён —
///   он проверял слух отдельно от смысла: игрок выбирал ту строчку, которая
///   похоже звучит, ничего не понимая.
/// * «Набор» — поле ввода — удалён вместе с экранной клавиатурой и правилом
///   «опечатка в одну букву засчитывается». Набор на телефоне на чужом языке
///   самое раздражающее место игры.
/// * **Вставка слов в предложение** — пропуски, плитки, сборка порядка —
///   удалена целиком вместе с самим понятием отдельного слова. Она проверяла
///   порядок слов, то есть грамматику, и требовала от контента разбора фразы
///   на слова, списка верных сборок и правила о том, что делать со знаками
///   препинания. Разговорнику это не нужно: фраза заучивается целиком.
enum GameMode {
  /// **a.** В центре фраза на изучаемом языке, вокруг шесть переводов.
  /// Проверяет понимание.
  pickNative,

  /// **b.** В центре фраза на родном языке, вокруг шесть фраз на изучаемом.
  /// Проверяет воспроизведение.
  pickTarget,

  /// **c.** Фраза звучит сама, как только круг открылся; нажатие на динамик
  /// проигрывает заново. Вокруг шесть переводов **на родном**. Проверяет
  /// восприятие на слух вместе со смыслом.
  listenNative;

  /// Код механики в `Reviews.mode`.
  String get code => name;

  /// Механика требует произвести фразу на изучаемом языке, а не узнать её.
  /// Отсюда растёт правило «горящей звезды»: она считается только здесь.
  bool get isProductive => this == GameMode.pickTarget;

  /// В центре звук, а не текст. Без голоса в системе такую механику
  /// планировать нельзя: круг без звука — это круг без задания.
  bool get needsAudio => this == GameMode.listenNative;

  /// Варианты на языке изучения. Иначе — на родном.
  bool get optionsInTargetLanguage => this == GameMode.pickTarget;

  static GameMode fromCode(String code) {
    for (final m in values) {
      if (m.name == code) return m;
    }
    // Неизвестный код бывает у строк, записанных прежними наборами режимов:
    // «circle», «tight», «typing», «listenTarget», «fillGaps», «buildPhrase».
    // Ничего в приложении их не читает, но если прочитает — самая нейтральная
    // механика та, в которую играют больше всего.
    return GameMode.pickTarget;
  }
}
