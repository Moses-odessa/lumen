/// Что именно учит игрок: слово или устойчивую фразу.
///
/// Различие появилось не сразу. Сначала памятью обладали только слова, а
/// фраза была «боссом» уровня — показывалась один раз и больше никогда не
/// возвращалась. Для словарного тренажёра это работало, для разговорника —
/// нет: заучить фразу нельзя, если её не повторяют.
///
/// Поэтому фраза стала такой же единицей памяти, как слово: у неё своё
/// состояние FSRS, своя яркость и своё место в очереди повторений.
enum ItemKind {
  word,
  phrase;

  String get code => name;

  /// Разбор кода из БД. Неизвестное значение — данные битые, но игру ломать
  /// не должно: считаем словом, потому что слов подавляющее большинство.
  static ItemKind fromCode(String? code) {
    for (final kind in values) {
      if (kind.name == code) return kind;
    }
    return ItemKind.word;
  }
}
