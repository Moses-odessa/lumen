import 'game_mode.dart';
import 'tier.dart';
import '../scoring/balance.dart';

/// Один вопрос: что в центре, что вокруг и что считается верным.
///
/// Геометрия экрана одна и та же во всех механиках — меняется только
/// содержимое этой структуры. Поэтому виджет не знает про механики ничего,
/// кроме того, что здесь написано.
///
/// **Один ответ, а не список.** Раньше здесь жили `answers` — по индексу на
/// каждый пропуск фразы, — и вместе с ними сборка предложения, список верных
/// порядков и сравнение собранного текста. Вставки слов в предложение больше
/// нет: единица изучения — фраза целиком, и вопрос у неё один, «какая из
/// шести». Всё, что обслуживало пропуски, ушло вместе с ними.
class CircleQuestion {
  const CircleQuestion({
    required this.itemId,
    required this.tier,
    required this.mode,
    required this.prompt,
    required this.options,
    required this.answerIndex,
    required this.lumens,
    this.isNew = false,
    this.promptSpeech,
    this.answerSpeech,
    this.promptTag,
    this.translation,
  });

  /// Идентификатор фразы: по нему у игрока лежит память о ней.
  final String itemId;

  /// Ярус фразы из `content.db`. Нужен при первом показе: строки состояния
  /// у неё ещё нет, и ярус взять больше неоткуда.
  final Tier tier;

  final GameMode mode;

  /// Что в центре: фраза или пустая строка, когда центр занимает звук.
  final String prompt;

  /// Пометка под центром кодом — сегодня это регистр фразы. Строку к коду
  /// даёт локализация, на языке интерфейса.
  ///
  /// Отдельно от свободного текста потому, что раньше это было одно поле — и
  /// в него уезжал то немецкий комментарий, написанный по-русски, то
  /// внутренний код `casual`. Набор кодов — `promptTags`.
  final String? promptTag;

  /// Шесть вариантов вокруг центра: сама фраза и пять других.
  ///
  /// Пять других — те, которые игрок **уже знает**. На этом стоит знакомство:
  /// новая фраза даётся среди знакомых, и игрок приходит к ответу
  /// исключением, а не подсказкой.
  final List<String> options;

  /// Индекс верного варианта в [options].
  final int answerIndex;

  /// Перевод фразы на родной язык: показывается вместе с ответом.
  ///
  /// В механике `pickNative` переводом и является верный вариант, поэтому там
  /// поле пустое: показывать ответ дважды незачем.
  final String? translation;

  /// Яркость фразы **до** этого ответа: от неё зависят очки.
  final Lumens lumens;

  /// Первый показ новой фразы: окна на ответ нет.
  ///
  /// Знакомство устроено методом исключения — вокруг новой фразы стоят пять
  /// уже известных, — и торопить тут нечего: чтобы прийти к ответу, игрок
  /// читает пять знакомых строчек.
  final bool isNew;

  /// Что произносится в центре — нужно механике на слух.
  final String? promptSpeech;

  /// Что произносится при верном соединении. Звучит в каждой механике: за
  /// пять минут игрок слышит полсотни образцов произношения, ничего для
  /// этого не делая.
  final String? answerSpeech;

  /// Тот же вопрос, но другой объект.
  ///
  /// Нужен затем, чтобы промах можно было показать заново. Арена сбрасывает
  /// своё состояние, когда `widget.question` перестаёт быть **тем же
  /// объектом** — сравнения по значению у вопроса нет и не надо: два круга по
  /// одной фразе это два разных вопроса, и путать их нельзя.
  ///
  /// Но забег возвращал промах в конец очереди тем же экземпляром. Пока за
  /// ним стояли другие круги, разница не проявлялась. А когда промах —
  /// последний круг забега, следующим показывается он же: объект тот, арена
  /// не сбрасывается, выбранный вариант остаётся на месте, и она больше не
  /// принимает ответов. Забег ждёт вечно.
  CircleQuestion again() => CircleQuestion(
        itemId: itemId,
        tier: tier,
        mode: mode,
        prompt: prompt,
        options: options,
        answerIndex: answerIndex,
        lumens: lumens,
        isNew: isNew,
        promptSpeech: promptSpeech,
        answerSpeech: answerSpeech,
        promptTag: promptTag,
        translation: translation,
      );

  /// Текст верного варианта.
  String get answer => answerIndex >= 0 && answerIndex < options.length
      ? options[answerIndex]
      : '';

  /// Верен ли выбор варианта.
  ///
  /// Сравнивается **текст**, а не только номер: два одинаковых варианта в
  /// круге — поломка, но если она случится, принять оба честнее, чем
  /// объявить один неверным.
  bool isCorrectOption(int index) {
    if (index == answerIndex) return true;
    if (index < 0 || index >= options.length) return false;
    return options[index] == answer;
  }
}
