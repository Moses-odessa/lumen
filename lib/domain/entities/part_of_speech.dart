/// Части речи и одно решение, которое из них следует: годится ли слово для
/// круга с вариантами.
///
/// Чистый Dart: ни Flutter, ни Drift.
library;

/// Служебные части речи. Круг из такого слова собрать нельзя.
///
/// У `sich` нет ни перевода одним словом, ни осмысленного набора «неверных
/// вариантов»: что поставить рядом с ним, чтобы выбор был честной задачей?
/// Ничего. То же с `der`, `nicht`, `doch`, с предлогами и числительными.
///
/// Но пропуск во фразе — ровно та форма, в которой предлоги и проверяют.
/// Поэтому служебные слова не исчезают из курса: они живут только в механиках
/// с пропуском, а звёздами на карте не становятся. В словнике из 6000 лемм
/// таких записей 156, и попытка сделать из каждой круг дала бы 156 заданий
/// без правильного ответа.
///
/// Набор дублируется с `functionWordPos` в `tool/content_sources.dart`:
/// `tool/` — отдельная программа и не тянет за собой `lib/`. Совпадение
/// проверяется тестом, а не вниманием.
const Set<String> functionWordPos = {
  'pronoun',
  'article',
  'determiner',
  'preposition',
  'conjunction',
  'particle',
  'interjection',
  'number',
};

/// Служебное ли это слово: пригодно только для механик с пропуском.
bool isFunctionWord(String pos) => functionWordPos.contains(pos);
