/// Калибровка: двадцать кругов с квотой по ярусам.
///
/// Спрашивать «какой у вас уровень?» бессмысленно — люди систематически
/// ошибаются в обе стороны. Вместо вопроса игрок сразу играет: та же механика
/// круга, те же жесты, только фразы со всех пяти ярусов.
///
/// **Тест не ищет ярус, а замеряет его.** Состав задан жёстко — по
/// [CalibrationBalance.quotaFor] кругов с каждого яруса, 6/5/4/3/2 снизу
/// вверх, всего [CalibrationBalance.testCircles], — и вопрос «куда шагнуть
/// дальше по результату» не задаётся ни разу. Это стратифицированная выборка:
/// с каждого яруса спрашивается столько, сколько задано, а ярус выводится из
/// того, как игрок отвечал ([Calibration.measure]). Больше проб внизу — потому
/// что у новичка граница решения лежит между A0 и A1, и потому что именно эти
/// фразы полезнее всего засеять.
///
/// Что здесь было раньше и что это охраняло:
///
/// * **Гребёнка** (`CalibrationPhase.comb`) — по одному кругу с яруса снизу
///   вверх до первого промаха. Она находила «вилку» знания за пять кругов и
///   заодно была лучшим туториалом: правила объясняются одним движением пальца
///   на понятном материале. Туториал пережил фазу — порядок кругов
///   восходящий по той же причине ([Calibration.plan]), — а вилка стала не
///   нужна: квота спрашивает все пять ярусов всегда.
/// * **Адаптивный поиск** (`search`) — два верных подряд поднимали пробу,
///   две ошибки опускали, 12–16 кругов. Он охранял точность на середине
///   шкалы: проб тратилось больше там, где решение под вопросом. Квота делает
///   то же самое, но заранее и без зависимости от порядка ответов; ценой
///   стала верхушка шкалы — см. запись про B2 в [CalibrationBalance.quotaFor].
/// * **Тройное подтверждение границы** (`confirm`) — найденный ярус
///   проверялся тремя кругами, потому что шесть вариантов дают 17 %
///   случайного попадания, и одним кругом ярус подтверждать нельзя. Правило
///   живо, только считается иначе: угадать три круга подряд можно с шансом
///   (1/6)³, а квоту целого яруса — практически нет
///   ([CalibrationBalance.tierPassShare]).
/// * **Засев** (`seed`) — хвост из 13–20 кругов, где ярус уже не менялся, а
///   верные ответы засевались в память с яркостью
///   [CalibrationBalance.seedLmMin]–[CalibrationBalance.seedLmMax]. Фаза
///   исчезла, но её работа — нет: засевает **каждый** из двадцати кругов, и
///   лекарство от холодного старта осталось на месте. Осталась и его цена, но
///   она стала другой: на сборке с одним запущенным A0 засеять можно только
///   спрошенное на A0, то есть шесть фраз вместо тринадцати-двадцати.
///   Знакомство устроено исключением, ему нужно пять — измерено и названо в
///   `calibration_diagnostic_test.dart`.
/// * **Фаза `phrases`** удалена ещё раньше: она спрашивала четыре целых
///   предложения на найденном ярусе и роняла ярус, если игрок собрал меньше
///   половины («знает слова, но не собирает предложения»). Единицей изучения
///   стала фраза, отдельных слов в игре нет — и весь тест теперь спрашивает
///   ровно то, что спрашивала эта фаза.
///
/// Вместе с фазами ушёл и `CalibrationPhase`: различать стало нечего. Экран
/// калибровки показывал подпись по фазе, и на его `switch` держалась проверка
/// «у новой фазы есть слова для игрока»; теперь подпись одна на весь тест.
///
/// Чистый Dart и чистая функция перехода: `answer(state, ...) → state`.
/// Благодаря этому алгоритм можно прогнать на тысяче синтетических «игроков»
/// с заданным истинным уровнем и измерить, как часто он ошибается — что и
/// требует критерий приёмки M3.
library;

import '../entities/game_mode.dart';
import '../entities/tier.dart';
import '../scoring/balance.dart';

/// Что показать игроку прямо сейчас.
class CalibrationStep {
  const CalibrationStep({
    required this.tier,
    required this.mode,
    this.isRepeat = false,
  });

  final Tier tier;
  final GameMode mode;

  /// Тематические варианты или созвучные.
  ///
  /// Поле обязано быть здесь, а не выводиться из механики. Раньше «тесный
  /// круг» был отдельным режимом, и правило «границу нужно подтвердить хотя
  /// бы раз созвучными» читалось как `mode == GameMode.tight`. После слияния
  /// круга и тесного круга в одну механику такая проверка не упала бы — она
  /// просто перестала бы срабатывать никогда, и каждая граница
  /// подтверждалась бы с шансом угадать один к шести. Тесты калибровки при
  /// этом остались бы зелёными.

  /// Переспрос подозрительно быстрого ответа: в зачёт не идёт.
  final bool isRepeat;

  /// Круг с созвучными вариантами: угадать вдвое труднее.
}

/// Состояние теста. Неизменяемое: каждый ответ порождает новое.
class CalibrationState {
  const CalibrationState({
    required this.ceiling,
    this.asked = 0,
    this.repeats = 0,
    this.correct = const {},
    this.pendingRepeat = false,
    this.result,
  });

  /// Начало теста: первый круг плана, то есть самый нижний ярус.
  ///
  /// [ceiling] обязателен, и значения по умолчанию у него нет намеренно.
  /// Разрешающая заглушка в этом самом месте уже стоила игроку яруса:
  /// `maxTierProvider` до ответа метаданных отдавал «все ярусы», калибровка
  /// читала потолок ровно один раз — в конце теста — и этим первым чтением
  /// сама же провайдер и инициализировала. На первом запуске ограничение не
  /// срабатывало никогда. Потолок обязан быть решением вызывающего, принятым
  /// до первого круга, а не значением, которое подставится само.
  factory CalibrationState.start({required Tier ceiling}) =>
      CalibrationState(ceiling: ceiling);

  /// Самый высокий ярус, который игроку можно выдать: запущенный и вычитанный.
  ///
  /// Живёт в состоянии, а не накладывается снаружи после теста. Прежнее
  /// основание — «засев спрашивает фразы выданного яруса, значит выданный
  /// ярус нужен раньше первой фразы засева» — ушло вместе с фазой засева:
  /// круги идут по плану, а не по выданному ярусу. Осталось второе, и его
  /// достаточно: зажим стал частью чистой функции и проверяется тестом. Тот
  /// его вид, что стоял тремя строчками в контроллере поверх
  /// `launchedTiersProvider`, не проверялся ничем — и не срабатывал.
  final Tier ceiling;

  /// Сколько зачётных кругов сыграно: ровно столько проб плана израсходовано.
  ///
  /// Это же число выбирает следующий круг ([probe]) — иначе «сколько
  /// спрошено» и «что спрашивать» могли бы разойтись.
  final int asked;

  /// Сколько было переспросов. Идут **сверх** [CalibrationBalance.testCircles]
  /// — см. [CalibrationBalance.maxRepeats].
  final int repeats;

  /// Верные ответы по ярусам: `ярус → сколько верных из его квоты`.
  ///
  /// Всё, что тест знает об игроке, лежит здесь, и правило вывода яруса
  /// читает только это ([Calibration.measure]). Порядок ответов не хранится
  /// нарочно: он не влияет на итог, и хранить его значило бы предложить
  /// следующему читателю сделать так, чтобы влиял.
  final Map<Tier, int> correct;

  /// Следующий круг — переспрос.
  final bool pendingRepeat;

  /// Измеренный ярус; `null`, пока тест не измерил его.
  ///
  /// Выставляется последним зачётным кругом — тогда же, когда тест кончается.
  /// Прежде запись шла раньше конца (на входе в засев), потому что фазе засева
  /// ярус был нужен для выбора фраз; фазы нет, и граница вернулась на своё
  /// место. Цена расхождения та же, что была: `_finish` в контроллере читает
  /// `result ?? Tier.a0`, поэтому незаписанный итог стоит игроку яруса.
  final Tier? result;

  /// Тест кончился ровно тогда, когда ярус измерен.
  ///
  /// Одно условие вместо двух: у теста нет состояния «ярус уже известен, а
  /// круги ещё идут», и появиться оно может только вместе с новым хвостом.
  bool get isDone => result != null;

  /// Ярусы, на которых игрок хоть раз ответил верно.
  ///
  /// Считается из [correct], а не хранится рядом: два поля про одно и то же
  /// расходятся молча. Сами фразы для засева собирает контроллер — он один
  /// знает их id; здесь ярусы, и по ним видно, докуда достаёт знание.
  Set<Tier> get confirmed => {
        for (final entry in correct.entries)
          if (entry.value > 0) entry.key,
      };

  /// Ярус, который проверяется сейчас.
  ///
  /// Выводится из плана и [asked], а не хранится: план — единственный
  /// источник порядка кругов. Пока идёт переспрос, [asked] не двигается, и
  /// круг остаётся на том же ярусе другой фразой — этого требует квота.
  ///
  /// Выхода за план не бывает: последняя проба выставляет [result], и с этого
  /// момента возвращается измеренный ярус.
  Tier get probe => result ?? Calibration.plan[asked];

  /// Ярус, который игрок получит: измеренный, урезанный до [ceiling].
  ///
  /// Экран итога показывает **оба** числа. Игрок, ответивший на B1 и
  /// получивший A0, обязан прочитать, почему, — иначе единственный доступный
  /// ему вывод такой: тест его не понял.
  Tier? get granted => result?.atMost(ceiling);

  /// Сколько кругов игрок **увидел**: пробы вместе с переспросами.
  ///
  /// Это число показывает экран итога: игрок считает экраны, а не зачёты.
  /// Каждый показанный круг прибавляет здесь ровно единицу — либо к [asked],
  /// либо (если ответ ушёл в переспрос) к [repeats].
  int get circles => asked + repeats;

  /// Что показать сейчас.
  CalibrationStep get step => CalibrationStep(
        tier: probe,
        isRepeat: pendingRepeat,
        // Механика одна на весь тест: назвать фразу на изучаемом языке.
        // Это самое требовательное из трёх, и мерить ярус надо им.
        mode: GameMode.pickTarget,
      );

  /// Прогресс теста 0..1 — для полосы на экране.
  ///
  /// Считаются **пробы**, а не показанные круги: показанных бывает больше
  /// двадцати (переспросы идут сверх квоты), и полоса от них либо перевалила
  /// бы за единицу, либо мерила бы длину, которая ещё не известна. Поэтому на
  /// переспросе полоса стоит — тот круг честно не продвинул тест ни на пробу.
  ///
  /// Прежняя полоса складывалась из долей фаз — 0,25 гребёнке, 0,45 поиску,
  /// 0,3 подтверждению, — и доля поиска мерилась от `searchCirclesMax`. На
  /// засев в ней не приходилось ничего, то есть полоса добиралась до конца к
  /// двадцатому кругу из тридцати и там стояла. Затем она считала показанные
  /// круги из тридцати — верно для теста, длина которого равнялась тридцати
  /// вместе с переспросами. Тест стал двадцатью пробами, и полоса приведена к
  /// нему: иначе она врала бы о том, сколько осталось.
  double get progress =>
      isDone ? 1 : asked / CalibrationBalance.testCircles;

  CalibrationState copyWith({
    // Потолок в `copyWith` не проходит: он решён до первого круга и по ходу
    // теста не меняется. Возможность подвинуть его на середине означала бы,
    // что половина теста прошла с одним ограничением, а итог достался по
    // другому — и объяснить игроку его ярус стало бы нечем.
    int? asked,
    int? repeats,
    Map<Tier, int>? correct,
    bool? pendingRepeat,
    Tier? Function()? result,
  }) =>
      CalibrationState(
        ceiling: ceiling,
        asked: asked ?? this.asked,
        repeats: repeats ?? this.repeats,
        correct: correct ?? this.correct,
        pendingRepeat: pendingRepeat ?? this.pendingRepeat,
        result: result == null ? this.result : result(),
      );
}

abstract final class Calibration {
  /// Порядок кругов: квота каждого яруса подряд, снизу вверх.
  ///
  /// **Восходящий, а не вперемешку, и это решение про туториал.** Онбординг —
  /// первое, что человек видит в игре, и первые шесть кругов должны объяснять
  /// правила, а не уровень языка. На A0 фраза длиной восемнадцать знаков, на
  /// B2 — до ста восемнадцати: круг, начавшийся с B2, учит новичка не жесту, а
  /// тому, что он ничего не понимает. Ровно этим была хороша удалённая
  /// гребёнка, и это её свойство здесь сохранено.
  ///
  /// Чем платим. Вперемешку было бы честнее как замер: восходящий порядок
  /// прозрачен (игрок замечает, что становится труднее, и к концу может начать
  /// тыкать), а фраз B2 достаётся самый усталый конец теста. Плата принята
  /// сознательно и стоит дешевле, чем кажется: правило вывода яруса читает
  /// только счёт верных по ярусам ([measure]) и от порядка не зависит вовсе, а
  /// осторожность вверху заложена в квоту — на B2 вывод вверх требует обоих
  /// верных, и «начал тыкать» ярус не поднимет.
  ///
  /// Сильному игроку восходящий порядок стоит шести тривиальных кругов в
  /// начале. Это цена за то, что слабый не встретит непонятную фразу до того,
  /// как понял, что от него хотят, — а слабых среди новых игроков больше, и
  /// квота наклонена в ту же сторону.
  static final List<Tier> plan = List.unmodifiable([
    for (final tier in Tier.values)
      for (var i = 0; i < CalibrationBalance.quotaFor(tier); i++) tier,
  ]);

  /// Правило вывода яруса.
  ///
  /// **Одной фразой:** ярус — та ступень, на которой накопленный снизу вверх
  /// перевес верных ответов над порогом угадывания
  /// ([CalibrationBalance.tierPassShare] от квоты) оказывается самым большим.
  ///
  /// Считается так: идём по ярусам снизу, каждому прибавляем
  /// `верных − 4/7 × квоты` и запоминаем, где сумма была выше всего. Ярус,
  /// пройденный целиком, прибавляет `3/7` своей квоты (A0 +2,57, B2 +0,86);
  /// ярус, отвеченный наугад, отнимает примерно столько же. Ничего
  /// положительного не набралось — ярус A0, ниже некуда.
  ///
  /// Правило одно, а охраняет две разные ошибки, и это главное, зачем оно
  /// именно такое:
  ///
  /// * **Осечка внизу не роняет игрока.** Знающий B2 ошибся на одном круге
  ///   A1: ярус всё равно прибавляет (4 верных из 5 — это +1,14), сумма
  ///   продолжает расти, итог B2. Больше того, терпимость шире одной осечки —
  ///   игрок, знающий B1 и проваливший **весь** A1 (один верный из пяти),
  ///   остаётся B1: просадка 1,86 меньше того, что прибавляют A2 и B1 (3,00).
  ///   Правило «самый высокий взятый ярус, ниже которого нет провалов» выдало
  ///   бы такому игроку A0, то есть ошибку на четыре яруса из-за пропуска в
  ///   школьной программе.
  /// * **Одна удача вверху не поднимает.** Новичок угадал две фразы B1 из
  ///   трёх (шанс 7 %): B1 прибавляет +0,29, но лежащие под ним A1 и A2
  ///   отняли от трёх до пяти — максимум остался на A0. Правило «самый
  ///   высокий взятый ярус» выдало бы B1, то есть ошибку на три яруса.
  ///
  /// Почему не проще. Оба простых правила были посчитаны на той же модели
  /// игрока (по 2000 синтетических прогонов на ярус, осечка 8 %, угадывание
  /// 1/6), и оба хуже:
  ///
  /// * «самый высокий взятый ярус» — 88,3 % точного попадания и 95,3 % ошибки
  ///   не больше яруса против 92,3 % и 99,4 % у накопленного перевеса.
  ///   Проигрывает он именно на удаче вверху: у игрока A0 ошибка укладывается
  ///   в ярус в 89 % забегов против 100 %.
  /// * «сколько ярусов взято минус один» — 86,3 % точного попадания.
  ///   Проигрывает на другом конце: у игрока A0 точное попадание 86 % против
  ///   97 %, потому что любая единственная удача наверху прибавляет ему ярус,
  ///   сколько бы ярусов под ней ни было провалено.
  ///
  /// Накопленный перевес выигрывает у обоих потому, что читает **и** удачу
  /// вверху, **и** провалы под ней, а не одно из двух.
  ///
  /// Функция публичная и берёт таблицу, а не состояние: правило обязано
  /// проверяться на выдуманных ответах, а не только на прогоне целого теста.
  static Tier measure(Map<Tier, int> correct) {
    var best = Tier.a0;
    // Ноль, а не минус бесконечность: A0 — дно шкалы, и ярус ниже него
    // выдать нельзя. Игрок, не набравший перевеса нигде, получает A0.
    var bestCredit = 0.0;
    var credit = 0.0;

    for (final tier in Tier.values) {
      credit += (correct[tier] ?? 0) -
          CalibrationBalance.tierPassShare * CalibrationBalance.quotaFor(tier);
      // Строгое сравнение: при равенстве остаётся ярус ниже. Ничьи редки, но
      // выбор в них — тот же, что во всём остальном проекте: завышенный ярус
      // отпугивает сильнее, чем заниженный утомляет.
      if (credit > bestCredit) {
        bestCredit = credit;
        best = tier;
      }
    }

    return best;
  }

  /// Применяет один ответ.
  ///
  /// [latency] нужна не для очков, а для защиты от угадывания: подозрительно
  /// быстрый верный ответ на незнакомом ярусе переспрашивается другой фразой.
  static CalibrationState answer(
    CalibrationState state, {
    required bool correct,
    required Duration latency,
  }) {
    if (state.isDone) return state;

    // Переспрос: результат прошлого круга не засчитан, этот идёт вместо него.
    // Второй раз подряд переспросить нельзя — иначе быстро отвечающий игрок
    // ходил бы по кругу, пока не кончится запас.
    if (state.pendingRepeat) {
      return _score(state.copyWith(pendingRepeat: false), correct);
    }

    // Защита от угадывания: верный ответ быстрее человеческого чтения на
    // ярусе, где игрок ещё ничего не взял, — это тык, а не знание.
    //
    // Прежде рядом стояло условие «до конца теста осталось не меньше двух
    // кругов»: переспрос входил в тридцать, стоил двух кругов (этот
    // незачтённый плюс замена) и у самого края съел бы последний ответ.
    // Переспросы вынесены за квоту, и охранять больше нечего — последнюю
    // пробу теперь можно переспросить безопасно.
    if (correct &&
        latency < CalibrationBalance.suspiciousLatency &&
        state.repeats < CalibrationBalance.maxRepeats &&
        _isAboveKnown(state)) {
      return state.copyWith(
        pendingRepeat: true,
        repeats: state.repeats + 1,
      );
    }

    return _score(state, correct);
  }

  /// Зачитывает ответ в квоту яруса и, если проб больше нет, объявляет ярус.
  ///
  /// Единственная концовка теста: пробы кончились. Прежде концовок было три —
  /// взятая гребёнка, набранные подтверждения границы, вторая осечка на нуле,
  /// — и каждая объявляла итог сама; тест кончался, когда сходился алгоритм,
  /// и забег, ответивший верно пять раз, укладывался в пять кругов. Состав
  /// теста задан заранее, сходимости нет, и конец у него один.
  static CalibrationState _score(CalibrationState state, bool correct) {
    final tier = state.probe;
    final tally = {...state.correct};
    if (correct) tally[tier] = (tally[tier] ?? 0) + 1;

    final asked = state.asked + 1;
    final next = state.copyWith(asked: asked, correct: tally);
    if (asked < plan.length) return next;

    return next.copyWith(result: () => measure(tally));
  }

  /// Ярус проверки выше всего, что игрок уже подтвердил.
  ///
  /// При восходящем порядке это означает «ярус, на котором игрок ещё ничего
  /// не взял»: как только там есть хоть один верный ответ, быстрый ответ
  /// перестаёт быть подозрительным — быстро отвечать на том, что знаешь,
  /// норма. Поэтому поводов для переспроса примерно столько, сколько ярусов
  /// игроку незнакомо, а не сколько кругов в тесте; сверху их всё равно
  /// закрывает [CalibrationBalance.maxRepeats]. Измерено: 2,6 переспроса на
  /// забег у игрока, который половину кругов отвечает быстрее порога
  /// (`calibration_diagnostic_test.dart`).
  static bool _isAboveKnown(CalibrationState state) {
    final probe = state.probe;
    return !state.confirmed.any((tier) => tier.index >= probe.index);
  }

  /// Кнопка «я с нуля»: A0 без теста.
  ///
  /// Потолок здесь A0 и без чтения метаданных: ниже нижнего яруса ничего нет,
  /// а сборки без запущенного A0 не существует — по такой играть было бы
  /// нечем. Значит и урезать нечего, и ждать провайдера незачем.
  ///
  /// Цена этой кнопки — пустая память: засеянных фраз у такого игрока нет, и
  /// первый его уровень честно окажется выбором из шести незнакомых. Это
  /// выбор игрока, а не оплошность кода.
  static CalibrationState fromScratch() => const CalibrationState(
        ceiling: Tier.a0,
        result: Tier.a0,
      );

  // `estimatedVocabulary` отсюда удалён.
  //
  // Он считал «сколько слов игрок уже знает» как размер созвездия по ярусу,
  // умноженный на тридцать созвездий, и на B2 давал ровно 2880 — при том, что
  // созвездий девять, а слов в базе 864. Экран результата обещал человеку
  // втрое больше, чем в приложении есть.
  //
  // Число теперь берётся из базы: сколько концептов на этом ярусе и ниже.
  // Курс растёт файлами контента, и обещание должно расти вместе с ним, а не
  // вместе с константой.
}
