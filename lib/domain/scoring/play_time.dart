/// Сколько игрок играл: время, дни и дни подряд.
///
/// Чистый Dart. Считается из журнала сессий целиком, а не из последних
/// записей: «всего времени» по последним шестидесяти строкам — это неправда,
/// показанная тому, кто играет второй год.
library;

/// Итоги по времени игры.
class PlayTime {
  const PlayTime({
    required this.total,
    required this.days,
    required this.streak,
    required this.sessions,
  });

  const PlayTime.empty()
      : total = Duration.zero,
        days = 0,
        streak = 0,
        sessions = 0;

  /// Сколько всего времени провёл в игре.
  ///
  /// **Это время с открытым приложением, а не время на задании.** Длительность
  /// сессии — стенные часы от начала уровня до его конца, и в неё попадает
  /// пауза, переслушивание и телефонный звонок посередине. Отдельно мерить
  /// время на задании можно, но это другая величина и другая работа; пока её
  /// нет, число нельзя подписывать словами, которых оно не заслуживает.
  final Duration total;

  /// Сколько разных дней игрок играл.
  final int days;

  /// Сколько дней подряд играет сейчас.
  ///
  /// Отдельная величина от «орбиты»: та — игровая механика со своими
  /// правилами роста и падения (день поднимает, пропуск опускает, три
  /// пропуска подряд обнуляют). Здесь простой факт календаря, который игрок
  /// может проверить сам.
  final int streak;

  /// Сколько сессий сыграно.
  final int sessions;

  bool get isEmpty => sessions == 0;

  /// Сколько времени в день в среднем — по дням, когда играл, а не по всем
  /// дням с установки.
  ///
  /// Второе было бы честнее к календарю и бесполезнее человеку: «в среднем
  /// четыре минуты в день» у того, кто играет по двадцать минут дважды в
  /// неделю, не описывает ни одного его дня.
  Duration get perDay => days == 0
      ? Duration.zero
      : Duration(milliseconds: total.inMilliseconds ~/ days);
}
