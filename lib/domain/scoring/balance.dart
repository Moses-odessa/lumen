/// Заход: цепочка уровней подряд, где каждый следующий чуть сложнее и
/// заметно дороже.
///
/// Почему заход, а не «уровень игрока». Аркадная петля — это не «через месяц
/// всё стало тяжелее», а «сколько выдержу за один присест». Бесконечно
/// растущая сложность через месяц сделала бы игру неиграбельной, а рекорд
/// часа — недостижимым. Заход обнуляется, когда игрок перестал играть, и
/// поэтому побить его можно всегда.
///
/// Провала в аркадном смысле здесь нет: в `score.dart` записано, что ошибка
/// стоит очков, но никогда не блокирует, и это правило сильнее жанра.
/// Аркадную форму даёт другое — слабый уровень сбрасывает множитель захода,
/// то есть игрок перестаёт зарабатывать эскалацию, но ничего не теряет.
abstract final class ClimbBalance {
  /// Прирост множителя очков за уровень: `k = 1 + step × (уровень − 1)`.
  ///
  /// Награда обгоняет сложность нарочно. На пятом уровне угадывание падает с
  /// 1/6 до 1/7, скоростное окно сжимается на пятую часть — а очки
  /// удваиваются. Если сделать наоборот, оптимальной игрой станет топтание
  /// на первом уровне, и вся аркадность умрёт. TODO(balance)
  static const double levelStep = 0.25;

  /// Потолок множителя: дальше сложность растёт, а награда нет.
  /// Достигается на девятом уровне. TODO(balance)
  static const double levelMultiplierMax = 3.0;

  /// Точность уровня, ниже которой множитель захода сбрасывается на первый.
  /// TODO(balance)
  static const double resetBelowAccuracy = 0.7;

  /// Перерыв, после которого заход считается закрытым. TODO(balance)
  static const Duration idleClosesClimb = Duration(minutes: 30);

  /// Сколько уровней добавляют один лишний вариант в круг. TODO(balance)
  static const int levelsPerExtraOption = 3;

  /// Потолок добавленных вариантов: восемь в круге — предел читаемости
  /// экрана, а не баланса. TODO(balance)
  static const int extraOptionsMax = 2;

  /// На сколько сжимается порог «автоматизма» за уровень и где он
  /// останавливается. Ниже 800 мс порог перестаёт мерить автоматизм и
  /// начинает мерить скорость пальца. TODO(balance)
  static const Duration speedTighteningPerLevel = Duration(milliseconds: 60);
  static const Duration speedFastestFloor = Duration(milliseconds: 800);

  /// Смещение к продуктивным режимам: из подходящих берётся лучший из N
  /// случайных, и N растёт с уровнем. TODO(balance)
  static const int modeDrawsBase = 2;
  static const int levelsPerExtraDraw = 2;
  static const int modeDrawsMax = 5;

  /// Насколько удлиняется забег и где останавливается. TODO(balance)
  static const int circlesPerRunGrowthEvery = 1;
  static const int circlesPerRunCap = 16;
}

/// Размеры сессий: круг → забег → уровень → ритуал.
abstract final class SessionBalance {
  /// Кругов в одном забеге. TODO(balance)
  static const int circlesPerRunMin = 10;
  static const int circlesPerRunMax = 14;

  /// Уровень: столько новых слов и столько повторов. TODO(balance)
  static const int newWordsPerLevel = 6;
  static const int reviewsPerLevel = 12;

  /// Забегов в уровне плюс один босс. TODO(balance)
  static const int runsPerLevel = 3;

  /// Планировщик берёт на сессию пул такого размера. TODO(balance)
  static const int sessionPoolSize = 40;

  /// Сколько раз новое слово показывается за уровень: первый показ без
  /// таймера плюс два вплетения в забеги. Отсюда и берётся длина забега:
  /// 6 новых × 3 + 12 повторов = 30 кругов на три забега по десять.
  /// TODO(balance)
  static const int newWordRepeats = 3;

  // `minGapBetweenRepeats` удалён вместе с раскладкой, которая его читала.
  //
  // Он задавал минимальный разрыв между двумя показами одного слова: без
  // разрыва второй показ проверял буфер кратковременной памяти, а не
  // повторение. Правило осталось в силе, но обеспечивается теперь не числом,
  // а структурой: каждый показ нового слова живёт на своём этапе, и между
  // ними лежит целый забег. Константа, которую никто не читает, — это
  // приглашение восстановить старую раскладку.

  /// Минимальная длина предложения для фразовой механики.
  ///
  /// Считается от закреплений, а не от полного числа перестановок. Плитка
  /// несёт заглавную и точку, поэтому первое и последнее слово стоят на
  /// месте, а внутренних расстановок у предложения из n слов ровно (n − 2)!:
  /// три слова дают **одну** — задания нет вовсе, — четыре дают две, пять
  /// шесть.
  ///
  /// Порог держится на четырёх, а не на пяти: пять отсекли бы 147 фраз из
  /// 432, то есть треть корпуса. Две расстановки — тонко, но это выбор из
  /// двух порядков, а не подстановка.
  ///
  /// Короткое предложение отбрасывает **выбор фразы**, а не сборка. Пока
  /// отбрасывала сборка, она возвращала `null`, загрузчик молча пропускал
  /// круг, и уровень заканчивался без обеих закрывающих фраз. TODO(balance)
  static const int phraseMinWords = 4;

  /// Сколько слов вынимается из предложения на самой лёгкой настройке.
  ///
  /// Два, а не одно, и это не осторожность. Один пропуск — это рамка с
  /// выбором: вокруг лежало бы одно слово, и задание вырождалось бы в
  /// подстановку. Два уже спрашивают порядок, то есть то, чего круг со словом
  /// не спрашивает вовсе. TODO(balance)
  static const int phraseGapsMin = 2;

  /// Сколько слов вынимается на самой трудной настройке.
  ///
  /// Ноль означает «все»: вынуто всё предложение, скелета не осталось. Это и
  /// есть «собери предложение» — не отдельная механика, а максимум этой же
  /// шкалы. TODO(balance)
  static const int phraseGapsAll = 0;

  /// Сколько вариантов на знакомстве с новым словом.
  ///
  /// Один. Выбирать не из чего, и круг перестаёт быть проверкой: игрок
  /// соединяет, слышит слово и видит перевод. Проверять то, чего человек ещё
  /// не видел, — это способ научить его, что игра непроходима. TODO(balance)
  static const int introductionOptions = 1;

  /// Восход: только повторения, столько времени. TODO(balance)
  static const Duration sunriseDuration = Duration(minutes: 2);

  /// Ограничение доли новых слов, когда игрок включил «свой темп» — иначе
  /// очередь повторений растёт быстрее, чем он способен её разгребать.
  /// TODO(balance)
  static const double maxNewWordShare = 0.35;
}

/// Этапы уровня: сколько вариантов показывает каждый и чем измеряется спринт.
///
/// Вариантность — шкала сложности, и её значения здесь означают именно
/// сложность, а не удобство раскладки. Один вариант это показ, шесть — 17 %
/// случайного попадания, и между ними лежит весь разбег, которым уровень
/// может распорядиться.
abstract final class StageBalance {
  /// Вариантов на этапах. TODO(balance)
  static const int consolidationOptions = 4;
  static const int checkOptions = 6;
  static const int reminderOptions = 5;
  static const int sprintOptions = 4;

  /// Очки за показ: круг с одним вариантом платит меньше.
  ///
  /// Не ноль. Ноль означал бы, что знакомство не считается игрой, и первые
  /// шесть кругов уровня шли бы «бесплатно» — а это те самые круги, где
  /// человек впервые видит слово. TODO(balance)
  static const double introductionScoreFactor = 0.4;

  /// Спринт: сколько верных связей за сколько времени. TODO(balance)
  static const int sprintConnections = 12;
  static const Duration sprintDuration = Duration(seconds: 45);

  /// Насколько поднимается планка на каждой следующей попытке.
  ///
  /// Растёт число связей, а не сжимается время: сжатое время превращает
  /// спринт в проверку скорости пальца. TODO(balance)
  static const int sprintConnectionsPerAttempt = 3;

  /// Сколько попыток спринта подряд. TODO(balance)
  static const int sprintAttempts = 3;

  /// Ниже этой яркости слово в спринт не идёт.
  ///
  /// Гонка на незнакомом материале учит панике, а не языку. Порог тот же, с
  /// которого включается скоростной множитель: спринт и есть измерение
  /// автоматизма, а измерять его там, где его заведомо нет, незачем.
  /// TODO(balance)
  static const Lumens sprintMinLumens = ScoreBalance.speedBonusMinLm;
}

/// Прогрессия: когда созвездие появляется, когда зажигается и когда пора
/// ярусом выше.
abstract final class ProgressionBalance {
  /// Сколько звёзд должно набраться у созвездия, чтобы оно появилось на
  /// карте яруса.
  ///
  /// Раньше здесь стояла таблица накопительных размеров — 12/24/48/72/96, — и
  /// точно такая же лежала в `tool/content_schema.dart`, где ею гейтилась
  /// сборка контента. Две копии одного правила в двух программах: правь одну,
  /// и вторая тихо начинает означать другое.
  ///
  /// Правила больше нет ни в одной копии, и не только из-за дублирования. На
  /// словнике из 6000 лемм точное равенство провалили бы десять тем из
  /// двадцати четырёх: у «денег» и «общества» на A0 по одному слову, и
  /// дотягивать их до двенадцати значило бы придумывать A0-лексику там, где
  /// её нет. Порог вместо равенства: тема ждёт того яруса, на котором ей есть
  /// что показать.
  ///
  /// Значение обязано совпадать с `minStarsForConstellation` в
  /// `tool/content_schema.dart`: `tool/` — отдельная программа и не тянет за
