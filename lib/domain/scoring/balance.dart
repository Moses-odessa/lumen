/// Калибровка и автокоррекция яруса на первых днях.
abstract final class CalibrationBalance {
  /// Сколько кругов спрашивается с каждого яруса. TODO(balance)
  ///
  /// **Решение владельца проекта, дословно:** «по онбоардингу давай сделаем 20
  /// фраз, только для слабее уровней будем ставить большее количество слов
  /// A0 - 6, A1 - 5, A2 - 4, B1 - 3, B2 - 2». Сумма квот и есть длина теста
  /// ([testCircles]), а сам тест из адаптивного поиска стал
  /// **стратифицированной выборкой**: с каждого яруса спрашивается столько,
  /// сколько здесь задано, и ярус выводится из того, как игрок отвечал
  /// ([tierPassShare]).
  ///
  /// Перекос вниз — не щедрость к слабому игроку, а место, где лежит решение.
  /// У новичка граница проходит между A0 и A1, и проб там нужно больше, чем
  /// сверху, где вывод один и тот же: «выше не берёт». Второе основание —
  /// засев: играть можно только по вычитанному, вычитан один A0
  /// (`content/launch.yaml`), и шесть нижних кругов оказываются **всем**
  /// запасом известного, с которым игрок выходит из онбординга (см.
  /// [seedLmMin] и `session_loader.dart`, `_optionPool`).
  ///
  /// Цена перекоса записана здесь же: на B2 проб две, и одна осечка — это
  /// половина яруса. Поэтому вывод вверх там требует обеих, и игрок, знающий
  /// B2 и промахнувшийся один раз, получает B1. Это осознанная ошибка в
  /// сторону вниз: завышенный ярус отпугивает сильнее, чем заниженный
  /// утомляет.
  ///
  /// `switch`, а не таблица `Map`: новый ярус в перечислении обязан **не
  /// собраться**, а не молча получить квоту ноль и выпасть из теста.
  static int quotaFor(Tier tier) => switch (tier) {
        Tier.a0 => 6,
        Tier.a1 => 5,
        Tier.a2 => 4,
        Tier.b1 => 3,
        Tier.b2 => 2,
      };

  /// Длина теста: сумма квот, то есть ровно двадцать зачётных кругов.
  ///
  /// Считаются **зачётные** круги — по одному на пробу. Показанных может быть
  /// до `testCircles + maxRepeats`: переспрос за подозрительно быстрый ответ
  /// идёт **сверх** двадцати, потому что квота — это число проб на ярусе, и
  /// съеденная переспросом проба означала бы, что B2 спрошен один раз вместо
  /// двух. Прежде переспрос входил в длину, и охраняло её отдельное правило
  /// «у самого края теста ответ засчитывается как есть»: последний круг
  /// нельзя было отдать переспросу, иначе тест кончился бы, выбросив
  /// единственный ответ, который в него попал. Правила больше нет — держать
  /// его стало нечем и незачем.
  ///
  /// Число перестало быть свободным. Здесь стояло `testCircles = 30`, и
  /// тридцать были взяты из засева: новая фраза даётся среди пяти уже
  /// известных, у нового игрока известного нет ничего, и тридцать засеянных
  /// фраз закрывали эту дыру. Двадцать — решение владельца, и оно двигает
  /// именно засев: на сборке с одним запущенным A0 засеять можно только то,
  /// что спрошено на A0, то есть шесть фраз вместо прежних тринадцати-двадцати
  /// (измерено `calibration_diagnostic_test.dart`). Знакомству нужно пять —
  /// запас сократился до одной фразы, и об этом надо знать, а не обнаружить
  /// это после релиза.
  static int get testCircles =>
      Tier.values.fold(0, (sum, tier) => sum + quotaFor(tier));

  /// Доля квоты, выше которой «знает ярус» правдоподобнее, чем «угадал».
  /// TODO(balance)
  ///
  /// Число не выбрано, а выведено, и вывод короткий. На своём ярусе игрок
  /// ошибается редко (осечка порядка 8 % — усталость, промах пальцем), на
  /// чужом попадает наугад один раз из [ScoreBalance.optionsPerCircle]. Верный
  /// ответ говорит в пользу «знает» с весом `ln(0.92·6) = 1.71`, промах — в
  /// пользу «угадывает» с весом `ln((5/6)/0.08) = 2.34`. Правдоподобия
  /// сравниваются на нуле, и порог доли верных выходит
  /// `2.34/(1.71+2.34) = 0.578` — четыре седьмых с точностью, которой хватает:
  /// на квотах 6/5/4/3/2 обе величины дают одни и те же пороги (4, 3, 3, 2, 2
  /// верных).
  ///
  /// Отсюда же берётся осторожность вверху, о которой говорит [quotaFor]: на
  /// квоте 2 порог 4/7 означает «оба верных», на квоте 6 — «четыре из шести».
  /// Чем меньше проб, тем строже требование, и это свойство доли, а не
  /// отдельное правило.
  static const double tierPassShare = 4 / 7;

  // Числа адаптивного поиска удалены вместе с ним: `combStepsMax`,
  // `searchCirclesMin`, `searchCirclesMax`, `correctToRise`, `errorsToFall`,
  // `borderConfirmations`.
  //
  // Они описывали тест, который **искал** ярус: гребёнка по одному кругу с
  // яруса до первого промаха, затем поиск (два верных подряд — вверх, две
  // ошибки — вниз), затем тройное подтверждение найденной границы, потому что
  // шесть вариантов дают 17 % случайного попадания и одним кругом ярус
  // подтверждать нельзя. Тест перестал искать: он спрашивает [quotaFor] проб
  // с каждого яруса и выводит ярус из накопленной точности. Защита от
  // угадывания вверх никуда не делась — её держит [tierPassShare], и держит
  // сильнее: три подтверждения подряд можно было угадать с шансом (1/6)³, а
  // квоту целого яруса — нет.
  //
  // `finalPhraseChecks` удалён раньше и по другой причине: он считал четыре
  // целых предложения на найденном ярусе, провал ронял ярус. Единицей
  // изучения стала фраза, и весь тест теперь спрашивает фразы — отдельная
  // проверка стала повтором самой себя.

  /// Подтверждённые фразы засеваются такой яркостью и сразу попадают в
  /// очередь повторений — не с нуля. TODO(balance)
  ///
  /// Полоса выбрана не за красоту: она выше
  /// [ScoreBalance.knownForEliminationLm] (35), и только поэтому засеянная
  /// фраза годится в варианты круга. Опусти её ниже — знакомство исключением
  /// снова окажется не из чего строить, а засев существует ровно затем, чтобы
  /// было.
  ///
  /// Отдельного хвоста под засев у теста больше нет: каждый из [testCircles]
  /// кругов делает оба дела сразу — мерит ярус и, если фраза лежит на
  /// выданном ярусе или ниже, засевает её. Прежде под засев отводились
  /// последние 13–20 кругов из тридцати, и это была отдельная фаза с
  /// собственным правилом обхода ярусов.
  ///
  /// Засевается только то, что лежит на **выданном** ярусе и ниже: фраза с
  /// закрытого яруса не светит нигде, потому что игрок туда не попадёт.
  static const Lumens seedLmMin = 50;
  static const Lumens seedLmMax = 60;

  /// Ответ быстрее этого на незнакомом ярусе подозрителен: скорее всего
  /// это тык наугад, попавший в цель. Такой круг переспрашивается другой
  /// фразой того же яруса и в зачёт не идёт. TODO(balance)
  static const Duration suspiciousLatency = Duration(milliseconds: 600);

  /// Сколько переспросов допускается за калибровку. Без ограничения игрок,
  /// который просто быстро отвечает, застрял бы в бесконечном тесте.
  /// TODO(balance)
  ///
  /// Переспросы идут **сверх** [testCircles]: проба, отданная переспросу,
  /// оставила бы ярус с меньшим числом проб, чем задано квотой, — а на B2 их
  /// и так две. Значит игрок видит от двадцати до двадцати четырёх кругов, и
  /// столько же показывает экран итога. Полоса прогресса при этом считает
  /// пробы, а не экраны: на переспросе она стоит.
  static const int maxRepeats = 4;

  /// Автокоррекция в первые дни: точность выше [suggestUpAccuracy] при
  /// медианном отклике до [suggestUpLatency] → предложение подняться;
  /// ниже [suggestDownAccuracy] → предложение опуститься. TODO(balance)
  static const double suggestUpAccuracy = 0.9;
  static const Duration suggestUpLatency = Duration(milliseconds: 1500);
  static const double suggestDownAccuracy = 0.5;
}

