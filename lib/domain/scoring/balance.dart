/// Яркость звезды в люменах: вероятность вспомнить слово прямо сейчас,
/// умноженная на 100. Производная величина от тройки FSRS.
typedef Lumens = int;

/// Полосы яркости из docs/CONCEPT.md. Границы — нижние, включительно.
enum LumenBand {
  /// 0–14: практически забыто, вернётся как новое.
  fading(0),

  /// 15–34: тускнеет, попадает в начало завтрашнего Восхода.
  dimming(15),

  /// 35–59: узнаёте, но не вспоминаете сами.
  flickering(35),

  /// 60–84: знаете уверенно, режимы на производство.
  steady(60),

  /// 85–100: всплывает мгновенно, повтор через недели.
  burning(85);

  const LumenBand(this.minLm);

  /// Нижняя граница полосы включительно. TODO(balance)
  final Lumens minLm;

  /// Полоса, в которую попадает данная яркость.
  static LumenBand of(Lumens lm) {
    var band = LumenBand.fading;
    for (final b in values) {
      if (lm >= b.minLm) band = b;
    }
    return band;
  }
}

/// Пороги и множители очков за одну связь:
/// `очки = base × k_speed × k_combo × k_mode`.
abstract final class ScoreBalance {
  /// Базовая стоимость верной связи. TODO(balance)
  static const int baseConnectionScore = 10;

  /// Скоростной множитель включается только начиная с этой яркости.
  /// Инвариант из README: на новом материале таймера нет вообще.
  /// TODO(balance)
  static const Lumens speedBonusMinLm = 40;

  /// Порог «автоматизма»: отклик быстрее — максимальный множитель.
  /// TODO(balance)
  static const Duration speedFastest = Duration(milliseconds: 1200);
  static const Duration speedFast = Duration(milliseconds: 2000);
  static const Duration speedMedium = Duration(milliseconds: 3500);

  /// Множители скорости по порогам выше. Штрафа за медленность нет.
  /// TODO(balance)
  static const double kSpeedFastest = 3.0;
  static const double kSpeedFast = 2.0;
  static const double kSpeedMedium = 1.5;
  static const double kSpeedSlow = 1.0;

  /// `k_combo = 1 + comboStep × подряд_верных`, но не больше [kComboMax].
  /// TODO(balance)
  static const double comboStep = 0.1;
  static const double kComboMax = 2.5;

  /// Быстрая ошибка дороже медленной: ответ быстрее [speedFastest],
  /// оказавшийся неверным, сбрасывает комбо до нуля и блокирует его рост
  /// на столько следующих связей. TODO(balance)
  static const int fastErrorComboLock = 3;

  /// Бонус к итогу забега за точность 100 %. TODO(balance)
  static const double perfectRunBonus = 1.25;

  /// Множитель механики. TODO(balance)
  ///
  /// Порядок отражает, сколько от игрока требуется: узнать фразу по тексту
  /// дешевле всего, узнать её на слух дороже, вспомнить и выбрать на
  /// изучаемом — дороже всего.
  ///
  /// Верхушка лестницы опустела дважды. «Набор» (2.0) ушёл вместе с полем
  /// ввода, фразовая сборка (2.2–2.5) — вместе с механикой вставки слов.
  /// Поднимать `pickTarget` за ними я не стал: множитель говорит, сколько
  /// требуется от игрока, а не сколько механик осталось.
  static double modeMultiplier(GameMode mode) => switch (mode) {
        GameMode.pickNative => 1.0,
        GameMode.listenNative => 1.4,
        GameMode.pickTarget => 1.6,
      };

  /// Диапазон яркости, на котором механика уместна. Планировщик выбирает
  /// механику по яркости фразы. TODO(balance)
  ///
  /// Верхний конец шкалы держит [GameMode.pickTarget]: до 75 lm там стоял он,
  /// а выше — `listenTarget`. Механики больше нет, и потолок пришлось поднять
  /// до 100, иначе самая выученная фраза спрашивалась бы самой дешёвой
  /// механикой.
  ///
  /// Вопрос на слух заодно поднят с 55 до 100 — он стал единственной
  /// механикой со звуком, и запирать его в тусклой половине неба значило бы,
  /// что выученная фраза больше никогда не звучит вопросом.
  static ({Lumens min, Lumens max}) modeLumenRange(GameMode mode) =>
      switch (mode) {
        GameMode.pickNative => (min: 0, max: 30),
        GameMode.listenNative => (min: 20, max: 100),
        GameMode.pickTarget => (min: 25, max: 100),
      };

  /// Митигация «узнавание вместо владения»: выше этой яркости режимы на
  /// узнавание не приносят очков вообще. TODO(balance)
  static const Lumens recognitionScoreCapLm = 40;

  /// «Горящая звезда»: столько верных подряд быстрее [burningLatency] в
  /// продуктивном режиме. TODO(balance)
  static const int burningFastStreak = 3;
  static const Duration burningLatency = Duration(milliseconds: 1500);

  /// Сколько вариантов в круге. Всегда шесть. TODO(balance)
  ///
  /// Число перестало быть шкалой сложности, и это следствие того, как теперь
  /// устроено знакомство. Новое даётся **методом исключения**: вокруг него
  /// стоят пять уже известных, и игрок понимает, какое шестое, потому что
  /// остальные пять узнаёт. Неполный круг ломает ровно это — при четырёх
  /// вариантах исключать приходится из четырёх, а при одном исключать нечего
  /// вовсе.
  ///
  /// Что было раньше и почему ушло:
  ///
  /// * `optionsMin = 1` — знакомство было **показом**: один вариант, соединил
  ///   и услышал. Проверять то, чего человек не видел, действительно нельзя,
  ///   но исключение — это не проверка, а способ показать. Игрок сам приходит
  ///   к ответу, и запоминается он лучше, чем прочитанный.
  /// * `defaultOptions(extra:)` и `ClimbBalance.extraOptionsMax` — заход
  ///   добавлял седьмой и восьмой вариант. Шкала сложности у захода осталась,
  ///   но другая: порог «автоматизма» и смещение к трудным механикам.
  static const int optionsPerCircle = 6;

  /// Яркость, с которой фраза считается известной настолько, чтобы стоять
  /// вокруг новой. TODO(balance)
  ///
  /// Полоса «узнаёте, но не вспоминаете сами» — её нижняя граница. Для
  /// исключения этого достаточно: узнать пять знакомых строчек легче, чем
  /// вспомнить любую из них. Требовать уверенного знания значило бы, что на
  /// первых уровнях исключать не из чего.
  static const Lumens knownForEliminationLm = 35;

  /// Сколько времени даётся на ответ, после чего верный вариант
  /// подсвечивается и произносится сам. TODO(balance)
  ///
  /// Смысл окна — учить отвечать быстро: правильный ответ, который игрок
  /// вспоминал двадцать секунд, в разговоре ему не поможет. Просрочка
  /// считается ответом «не вспомнил»: слово тускнеет и возвращается в
  /// очередь.
  ///
  /// **На знакомстве окна нет.** Там вокруг стоят пять известных и одно
  /// новое, и чтобы прийти к ответу исключением, игроку надо прочитать пять
  /// знакомых строчек — торопить его в этот момент значит требовать угадать,
  /// а не сообразить.
  static const Duration answerWindow = Duration(seconds: 5);

}

/// Память: как время отклика превращается в оценку и какую вероятность
/// вспомнить планировщик считает достаточной.
abstract final class SrsBalance {
  /// Ответ быстрее — «легко»: игрок не вспоминал, а знал. TODO(balance)
  static const Duration gradeEasyBelow = Duration(milliseconds: 1200);

  /// Ответ быстрее — «хорошо». Медленнее — «трудно»: вспомнил, но с усилием,
  /// и это ровно тот материал, который стоит показать раньше. TODO(balance)
  static const Duration gradeGoodBelow = Duration(milliseconds: 2000);

  /// Целевая вероятность вспомнить на момент следующего повтора. Стандарт
  /// FSRS — 0.9; ниже даёт более длинные интервалы ценой забывания.
  /// TODO(balance)
  static const double targetRetention = 0.9;

  /// Границы стабильности в днях: ниже первой FSRS вырождается в нули, выше
  /// второй интервалы уходят за горизонт осмысленного планирования.
  static const double minStability = 0.01;
  static const double maxStability = 36500;

  /// Границы сложности: шкала FSRS 1..10.
  static const double minDifficulty = 1;
  static const double maxDifficulty = 10;

  /// Повторы внутри одного дня считаются «коротким» интервалом: слово ещё в
  /// рабочей памяти, и обычная формула стабильности к нему неприменима.
  static const Duration sameDayWindow = Duration(hours: 12);
}

/// Заход: цепочка уровней подряд, где каждый следующий чуть сложнее и
/// заметно дороже.
///
/// Почему заход, а не «уровень игрока». Аркадная петля — это не «через месяц
/// всё стало тяжелее», а «сколько выдержу за один присест». Бесконечно
/// растущая сложность через месяц сделала бы игру неиграбельной, а рекорд
/// часа — недостижимым. Заход обнуляется, когда игрок перестал играть, и
/// поэтому побить его можно всегда.
///
/// Провала в аркадном смысле здесь нет: в `score.dart` записано, что ошибка
/// стоит очков, но никогда не блокирует, и это правило сильнее жанра.
/// Аркадную форму даёт другое — слабый уровень сбрасывает множитель захода,
/// то есть игрок перестаёт зарабатывать эскалацию, но ничего не теряет.
abstract final class ClimbBalance {
  /// Прирост множителя очков за уровень: `k = 1 + step × (уровень − 1)`.
  ///
  /// Награда обгоняет сложность нарочно. На пятом уровне угадывание падает с
  /// 1/6 до 1/7, скоростное окно сжимается на пятую часть — а очки
  /// удваиваются. Если сделать наоборот, оптимальной игрой станет топтание
  /// на первом уровне, и вся аркадность умрёт. TODO(balance)
  static const double levelStep = 0.25;

  /// Потолок множителя: дальше сложность растёт, а награда нет.
  /// Достигается на девятом уровне. TODO(balance)
  static const double levelMultiplierMax = 3.0;

  /// Точность уровня, ниже которой множитель захода сбрасывается на первый.
  /// TODO(balance)
  static const double resetBelowAccuracy = 0.7;

  /// Перерыв, после которого заход считается закрытым. TODO(balance)
  static const Duration idleClosesClimb = Duration(minutes: 30);

  // `levelsPerExtraOption` и `extraOptionsMax` удалены вместе со шкалой
  // вариантности: вариантов в круге теперь всегда шесть, потому что на
  // полном круге держится знакомство методом исключения. Заход по-прежнему
  // повышает сложность, но двумя другими ручками — порогом «автоматизма» и
  // смещением к трудным механикам.

  /// На сколько сжимается порог «автоматизма» за уровень и где он
  /// останавливается. Ниже 800 мс порог перестаёт мерить автоматизм и
  /// начинает мерить скорость пальца. TODO(balance)
  static const Duration speedTighteningPerLevel = Duration(milliseconds: 60);
  static const Duration speedFastestFloor = Duration(milliseconds: 800);

  /// Смещение к продуктивным режимам: из подходящих берётся лучший из N
  /// случайных, и N растёт с уровнем. TODO(balance)
  static const int modeDrawsBase = 2;
  static const int levelsPerExtraDraw = 2;
  static const int modeDrawsMax = 5;

  /// Насколько удлиняется забег и где останавливается. TODO(balance)
  static const int circlesPerRunGrowthEvery = 1;
  static const int circlesPerRunCap = 16;
}

/// Размеры сессий: круг → забег → уровень → ритуал.
abstract final class SessionBalance {
  /// Кругов в одном забеге. TODO(balance)
  static const int circlesPerRunMin = 10;
  static const int circlesPerRunMax = 14;

  /// Уровень: столько новых слов и столько повторов. TODO(balance)
  static const int newWordsPerLevel = 6;
  static const int reviewsPerLevel = 12;

  /// Забегов в уровне плюс один босс. TODO(balance)
  static const int runsPerLevel = 3;

  /// Планировщик берёт на сессию пул такого размера. TODO(balance)
  static const int sessionPoolSize = 40;

  /// Сколько раз новое слово показывается за уровень: первый показ без
  /// таймера плюс два вплетения в забеги. Отсюда и берётся длина забега:
  /// 6 новых × 3 + 12 повторов = 30 кругов на три забега по десять.
  /// TODO(balance)
  static const int newWordRepeats = 3;

  // `minGapBetweenRepeats` удалён вместе с раскладкой, которая его читала.
  //
  // Он задавал минимальный разрыв между двумя показами одного слова: без
  // разрыва второй показ проверял буфер кратковременной памяти, а не
  // повторение. Правило осталось в силе, но обеспечивается теперь не числом,
  // а структурой: каждый показ нового слова живёт на своём этапе, и между
  // ними лежит целый забег. Константа, которую никто не читает, — это
  // приглашение восстановить старую раскладку.

  // Числа фразовой механики удалены вместе с ней: `phraseMinWords`,
  // `phraseGapsMin`, `phraseGapsAll`. Они описывали, из какого предложения
  // можно вынуть слова и сколько именно вынуть, — вставки слов в предложение
  // в игре больше нет.
  //
  // `introductionOptions = 1` удалён отдельно, и это не следствие, а решение.
  // Знакомство было показом: один вариант, соединил и услышал. Теперь оно
  // устроено исключением — вокруг новой фразы стоят пять известных, — и
  // неполный круг ломал бы ровно это.

  /// Восход: только повторения, столько времени. TODO(balance)
  static const Duration sunriseDuration = Duration(minutes: 2);

  /// Ограничение доли новых слов, когда игрок включил «свой темп» — иначе
  /// очередь повторений растёт быстрее, чем он способен её разгребать.
  /// TODO(balance)
  static const double maxNewWordShare = 0.35;
}

/// Сколько круг стоит открытым после ответа, прежде чем развернётся
/// следующий.
///
/// Отдельный класс, а не константа в контроллере: это игровое число, и
/// правило проекта требует держать такие в одном месте. Пока 420 мс и 1100 мс
/// лежали внутри `RunController`, у калибровки не было **никакой** паузы — то
/// есть два пути игры разошлись молча, ровно так, как это правило и
/// предотвращает.
abstract final class RevealBalance {
  /// Верный ответ: подсветка и озвучка, читать нечего. TODO(balance)
  static const Duration correct = Duration(milliseconds: 420);

  /// Ошибка и просроченное окно: надо успеть увидеть и услышать верный
  /// вариант, иначе промах ничему не учит. Просрочка — это тот же промах, и
  /// пауза у неё та же. TODO(balance)
  static const Duration wrong = Duration(milliseconds: 1100);

  /// Пауза после ответа. Один вход для забега и калибровки.
  ///
  /// Прежде здесь были ещё два значения, для фразовой сборки: там пауза
  /// держала перевод и озвучку целого предложения. Механики нет, значений
  /// нет, а `forMode` осталась ровно потому, что оба пути игры обязаны
  /// спрашивать паузу в одном месте.
  static Duration forMode(GameMode mode, {required bool correct}) =>
      correct ? RevealBalance.correct : wrong;
}

/// Этапы уровня: чем платит знакомство и чем измеряется спринт.
///
/// **Вариантность отсюда ушла.** Здесь стояли `consolidationOptions = 4`,
/// `checkOptions = 6`, `reminderOptions = 5`, `sprintOptions = 4` — этап
/// выбирал сложность числом вариантов, от одного (показ) до шести (17 %
/// случайного попадания). Теперь круг всегда шестивариантный: на полном круге
/// держится знакомство методом исключения, и урезанный круг ломал бы его —
/// исключать было бы не из чего. Числа не переехали в другое место, они
/// перестали существовать; читать их к этому моменту уже никто не читал.
abstract final class StageBalance {
  /// Очки за знакомство: первая встреча с фразой платит меньше.
  ///
  /// Не ноль. Ноль означал бы, что знакомство не считается игрой, и первые
  /// шесть кругов уровня шли бы «бесплатно» — а это те самые круги, где
  /// человек впервые видит фразу.
  ///
  /// Прежнее объяснение было «круг с одним вариантом платит меньше», и оно
  /// перестало быть правдой: вариантов шесть и на знакомстве. Скидка осталась
  /// потому, что дело не в числе вариантов, а в том, что игрок не вспоминает,
  /// а узнаёт впервые. TODO(balance)
  static const double introductionScoreFactor = 0.4;

  /// Спринт: сколько верных связей за сколько времени. TODO(balance)
  static const int sprintConnections = 12;
  static const Duration sprintDuration = Duration(seconds: 45);

  /// Насколько поднимается планка на каждой следующей попытке.
  ///
  /// Растёт число связей, а не сжимается время: сжатое время превращает
  /// спринт в проверку скорости пальца. TODO(balance)
  static const int sprintConnectionsPerAttempt = 3;

  /// Сколько попыток спринта подряд. TODO(balance)
  static const int sprintAttempts = 3;

  /// Ниже этой яркости слово в спринт не идёт.
  ///
  /// Гонка на незнакомом материале учит панике, а не языку. Порог тот же, с
  /// которого включается скоростной множитель: спринт и есть измерение
  /// автоматизма, а измерять его там, где его заведомо нет, незачем.
  /// TODO(balance)
  static const Lumens sprintMinLumens = ScoreBalance.speedBonusMinLm;
}

/// Прогрессия: когда созвездие появляется, когда зажигается и когда пора
/// ярусом выше.
abstract final class ProgressionBalance {
  /// Сколько звёзд должно набраться у созвездия, чтобы оно появилось на
  /// карте яруса.
  ///
  /// Раньше здесь стояла таблица накопительных размеров — 12/24/48/72/96, — и
  /// точно такая же лежала в `tool/content_schema.dart`, где ею гейтилась
  /// сборка контента. Две копии одного правила в двух программах: правь одну,
  /// и вторая тихо начинает означать другое.
  ///
  /// Правила больше нет ни в одной копии, и не только из-за дублирования. На
  /// словнике из 6000 лемм точное равенство провалили бы десять тем из
  /// двадцати четырёх: у «денег» и «общества» на A0 по одному слову, и
  /// дотягивать их до двенадцати значило бы придумывать A0-лексику там, где
  /// её нет. Порог вместо равенства: тема ждёт того яруса, на котором ей есть
  /// что показать.
  ///
