/// Что показывает экран забега прямо сейчас.
enum RunPhase {
  /// Круг открыт, ждём ответа.
  asking,

  /// Ответ принят: подсветка и озвучка. Круг стоит открытым, пока ответ
  /// дозвучивает ([RunController._holdCircle]), а нажатие по арене закрывает
  /// эту паузу досрочно ([RunController.skipReveal]).
  revealing,

  /// Забег закончен.
  finished,
}

/// Состояние забега.
class RunState {
  const RunState({
    required this.queue,
    required this.index,
    required this.phase,
    required this.score,
    required this.combo,
    required this.correct,
    required this.answered,
    required this.total,
    this.lastCorrect,
    this.summary,
    this.stage,
    this.goal,
    this.window,
  });

  const RunState.empty()
      : queue = const [],
        index = 0,
        phase = RunPhase.finished,
        score = 0,
        combo = const ComboState(),
        correct = 0,
        answered = 0,
        total = 0,
        lastCorrect = null,
        summary = null,
        stage = null,
        goal = null,
        window = null;

  /// Очередь кругов. Ошибочные слова возвращаются в её конец, поэтому она
  /// длиннее исходного плана.
  final List<CircleQuestion> queue;

  final int index;
  final RunPhase phase;
  final int score;
  final ComboState combo;

  /// Верных ответов и всего данных ответов.
  final int correct;
  final int answered;

  /// Кругов в исходном плане — по нему рисуется прогресс.
  final int total;

  /// Итог последнего ответа: для подсветки.
  final bool? lastCorrect;

  final RunSummary? summary;

  /// Этап уровня, на котором идёт забег. `null` у Восхода.
  final LevelStage? stage;

  /// Цель спринта. `null` у обычного забега.
  final SprintGoal? goal;

  /// Окно на ответ, открытое **прямо сейчас**; `null` — окна нет.
  ///
  /// Это то самое значение, которым заведён таймер забега, и лежит оно в
  /// состоянии затем, чтобы полоса окна над ареной брала длину отсюда. Прежде
  /// полоса завела свою анимацию на `ScoreBalance.answerWindow`, а таймер —
  /// свой `Timer` на то же число: совпадали они случайно и разошлись бы от
  /// любой правки. Теперь длину считает один геттер
  /// ([CircleQuestion.answerWindow]), заводит таймер один метод, и полоса
  /// показывает его, а не себя.
  ///
  /// `null` бывает по четырём причинам, и во всех четырёх полосы нет тоже:
  /// знакомство (торопить нельзя), пауза после ответа (отвечать уже нечего),
  /// круг на слух, пока фраза звучит (отвечать ещё нечего), и забег заморожен
  /// ([RunController.freeze]) — игрока перед кругом нет вовсе.
  final Duration? window;

  /// Спринт: цель достигнута.
  bool get goalReached => goal?.reachedBy(correct) ?? false;

  CircleQuestion? get current =>
      index >= 0 && index < queue.length ? queue[index] : null;

  bool get isFinished => phase == RunPhase.finished;

  /// Прогресс забега 0..1 — по отвеченным кругам плана, а не по очереди:
  /// иначе полоса ползла бы назад на каждой ошибке.
  ///
  /// У спринта та же формула означает путь к планке: `total` там равен числу
  /// нужных связей, а не длине очереди.
  double get progress => total == 0 ? 0 : (answered / total).clamp(0.0, 1.0);

  RunState copyWith({
    List<CircleQuestion>? queue,
    int? index,
    RunPhase? phase,
    int? score,
    ComboState? combo,
    int? correct,
    int? answered,
    int? total,
    bool? Function()? lastCorrect,
    RunSummary? summary,
    LevelStage? stage,
    SprintGoal? goal,
    Duration? Function()? window,
  }) =>
      RunState(
        queue: queue ?? this.queue,
        index: index ?? this.index,
        phase: phase ?? this.phase,
        score: score ?? this.score,
        combo: combo ?? this.combo,
        correct: correct ?? this.correct,
        answered: answered ?? this.answered,
        total: total ?? this.total,
        lastCorrect:
            lastCorrect == null ? this.lastCorrect : lastCorrect(),
        summary: summary ?? this.summary,
        stage: stage ?? this.stage,
        goal: goal ?? this.goal,
        window: window == null ? this.window : window(),
      );
}

/// Забег: 10–14 кругов подряд, темп которых задаёт озвучка.
///
/// Четыре вещи, которые здесь важнее всего:
///
/// 1. **Темп круга — это звук.** Обе границы круга стоят по озвучке, и обе
///    считаются в этом файле: окно на ответ открывается, когда дозвучал центр
///    (до него отвечать не на что, [_beginCircle]), а закрывается круг, когда
///    дозвучал ответ ([_holdCircle]). Прежде звук «запускался и забывался», и
///    оба конца были числами: окно шло сквозь озвучку центра, а ответ
///    дозвучивал поверх следующего круга.
/// 2. **Запись в базу не блокирует.** FSRS-обновление уходит в фон: игрок не
///    должен ждать диск между кругами.
/// 3. **Ошибка не блокирует.** Слово возвращается в конец очереди и теряет
///    яркость, но забег продолжается. Жизней в игре нет.
/// 4. **Забег не идёт без игрока.** Ни один таймер круга не бежит, пока игрока
///    перед кругом нет — приложение ушло с экрана или круг закрыт вопросом
///    «точно прервать?», — и это время забегу не принадлежит ([freeze]).
///
/// Ожидание звука тем не менее нигде не бесконечно: у окна сигнал приходит и
/// с молчащего устройства (`SpeechOutcome.done` — «говорить было нечем»), у
/// паузы поверх этого стоит свой верх ([RevealBalance.ceiling]). Забег не
/// вправе зависеть от того, дойдёт ли до него чужой сигнал.
class RunController extends Notifier<RunState> {
  /// Окно на ответ. `null` — окна нет: знакомство, пауза, звучащий центр или
  /// приложение вне экрана.
  Timer? _windowTimer;

  /// Низ паузы после ответа: раньше него круг не закрывается никогда.
  ///
  /// Отдельный таймер, а не отсчёт по часам, и это условие, а не вкус. Пауза
  /// кончается, когда прошло **и** то, и другое — низ и озвучка, — а сложить
  /// два ожидания без общих часов можно только так. Считать остаток низа по
  /// `DateTime.now()` значило бы мерить паузу настоящими часами там, где всё
  /// остальное в забеге живёт по таймерам, и первым это заметил бы не игрок, а
  /// тест на поддельном времени.
  ///
  /// Он же и единственная ручка, которой паузу можно снять: отменённый таймер
  /// не даёт ожиданию досчитать вовсе ([freeze], [_advance]).
  Timer? _revealTimer;

  /// Кто сообщает, что приложение ушло с экрана и вернулось.
  ///
  /// Слушатель живёт в контроллере, а не в виджете, и это не вкус.
  /// `AppLifecycleListener` виджета не требует, а таймеры круга живут здесь —
  /// значит здесь и место тому, кто их останавливает. Посредник-виджет добавил
  /// бы третье место, в котором забег способен оказаться живым, пока игрок на
  /// него не смотрит: экран сняли с дерева, а таймер тикает.
  ///
  /// Причин заморозки при этом больше, чем одна эта: вторую приносит экран
  /// ([freeze]), потому что знать про диалог поверх круга слушателю не дано.
  AppLifecycleListener? _lifecycle;

  /// Забег заморожен: игрока перед кругом нет. Пока `true`, забег не заводит
  /// ни таймеров, ни озвучки.
  bool _frozen = false;

  /// Когда заморозили — чтобы вернуть забегу его срок.
  DateTime? _frozenAt;

  @override
  RunState build() {
    _lifecycle = AppLifecycleListener(onStateChange: _screenChanged);
    ref.onDispose(() {
      _windowTimer?.cancel();
      // И пауза тоже: её низ — таймер, а ожидание, которому не дали
      // досчитать, к состоянию уже не потянется.
      _revealTimer?.cancel();
      _lifecycle?.dispose();
      _lifecycle = null;
    });
    return const RunState.empty();
  }

  /// Начинает забег по готовому списку кругов.
  ///
  /// [maxDuration] ограничивает забег по времени, а не по числу кругов —
  /// так устроен Восход: две минуты повторений, сколько успеется. Круг,
  /// начатый до истечения времени, всегда доигрывается: обрывать человека
  /// на середине ответа — это способ научить его не начинать.
  /// [climb] — уровень захода, на котором идёт забег. `null` для Восхода:
  /// он не про очки, а про то, что часть неба снова горит.
  /// [stage] — этап уровня, на котором идёт забег: от него зависит цена
  /// круга (показ платит меньше проверки). [goal] задан только у спринта: с
  /// ним забег кончается по достигнутой планке или по истечению времени, а не
  /// по концу очереди.
  void start(
    List<CircleQuestion> questions, {
    Duration? maxDuration,
    ClimbState? climb,
    LevelStage? stage,
    SprintGoal? goal,
  }) {
    _windowTimer?.cancel();
    // Пауза прошлого забега новому не принадлежит: её ожидание всё равно
    // сверило бы круг и промолчало, но таймер, доживший до нового забега, —
    // это отсчёт, о котором никто не просил.
    _revealTimer?.cancel();
    _lmGained = 0;
    // Флаг переслушивания живёт на круге, а не на забеге: без сброса новый
    // забег наследовал бы его с последнего круга предыдущего.
    _replayed = false;
    // У спринта время своё: планка в связях, а срок — в цели.
    final limit = goal?.duration ?? maxDuration;
    _deadline = limit == null ? null : DateTime.now().add(limit);
    _startedAt = DateTime.now();

    if (questions.isEmpty) {
      state = const RunState.empty();
      return;
    }

    _run = RunScore(
      difficulty: climb?.difficulty,
      climbMultiplier: climb?.multiplier ?? 1.0,
      stageFactor: stage == null ? 1.0 : StageRules.scoreFactorFor(stage),
    );
    state = RunState(
      queue: List.of(questions),
      index: 0,
      phase: RunPhase.asking,
      score: 0,
      combo: const ComboState(),
      correct: 0,
      answered: 0,
      // У спринта полоса прогресса показывает путь к планке, а не к концу
      // очереди: кругов в очереди намеренно вдвое больше, чем нужно связей.
      total: goal?.connections ?? questions.length,
      stage: stage,
      goal: goal,
    );

    ref.read(analyticsProvider).log(AnalyticsEvents.runStarted, {
      'circles': questions.length,
      'climb_level': climb?.level ?? 0,
      'stage': stage?.name ?? '',
    });
    _beginCircle();
  }

  /// Сколько кругов задано — для точности уровня целиком.
  int get circles => _run.circles;

  RunScore _run = RunScore();

  /// Когда забег обязан закончиться; `null` — играем всю очередь.
  DateTime? _deadline;

  DateTime _startedAt = DateTime.now();

  /// Сколько длился забег — уходит в журнал сессий.
  Duration get elapsed => DateTime.now().difference(_startedAt);

  /// Ответ выбором варианта — единственный способ ответить.
  ///
  /// Второй был: `answerSlots` принимал расстановку слов по пропускам фразы.
  /// Вместе с ним ушла и защита от того, чтобы многослотовый вопрос попал
  /// сюда, — она стерегла реальную дыру, в которой фраза с двумя пропусками
  /// засчитывалась бы полностью верной от одного тапа. Слот теперь один, и
  /// стеречь нечего.
  void answerOption(int index, Duration latency) {
    final question = state.current;
    if (question == null || state.phase != RunPhase.asking) return;
    _submit(question, question.isCorrectOption(index), latency);
  }

  // ── Темп круга ───────────────────────────────────────────────────────────

  /// Открывает круг: озвучка центра и окно на ответ.
  ///
  /// Порядок здесь и есть починка «на ответ дают две секунды вместо пяти».
  /// Прежде в этом месте подряд стояли `_speakPrompt()` и `_openWindow()`, и на
  /// круге со слухом часы начинали тикать вместе с озвучкой. Фраза существует
  /// там только как звук: пока она произносится — две-три секунды на
  /// предложение, — отвечать физически не на что, и от пяти секунд игроку
  /// оставалось две. Просрочка при этом считается «не вспомнил».
  ///
  /// Поэтому у текстового центра окно открывается сразу (отвечать можно с
  /// первого кадра), а у звучащего — по сигналу окончания озвучки.
  ///
  /// Первое проигрывание делает игра, а не игрок: без этого механика на слух
  /// начиналась тишиной — игрок видел динамик и должен был сообразить, что по
  /// нему надо нажать, хотя задание в том, чтобы узнать фразу, а не догадаться,
  /// как её услышать. И это же держит скоростной множитель: «переслушал» ставит
  /// только [replayPrompt], то есть повторное нажатие.
  void _beginCircle() {
    // У замороженного забега круг не открывается вовсе: ни звука, ни отсчёта.
    if (_frozen) return;
    _preloadNext();
    final prompt = state.current?.promptSpeech;
    if (prompt == null) {
      _openWindow();
      return;
    }
    unawaited(_speakThenOpen(prompt));
  }

  /// Произносит центр и открывает окно, когда дозвучал **этот** центр.
  ///
  /// Сторожа здесь два, и они про разное.
  ///
  /// Первый — исход произнесения. Окно открывает только то произнесение, после
  /// которого наступила тишина ([SpeechOutcome.done]); вытесненное молчит.
  /// Прежде на этом месте стояла проверка круга — «тот же вопрос, что был?» —
  /// и она пропускала оба пути, на которых круг тот же, а звучит уже второе
  /// чтение: переслушивание и повтор после возвращения на экран. Замер сверки:
  /// озвучка 3 с, уход в фон на первой секунде, возврат на второй — окно
  /// открывалось на третьей, пока второе чтение шло до пятой. То есть правило,
  /// ради которого всё это делалось («часы не идут, пока фраза звучит»), на
  /// двух путях из трёх не работало. Вытеснившее произнесение откроет окно
  /// само — своим сигналом, а не чужим.
  ///
  /// Второй — круг. Он стережёт то, чего исход не видит: пока фраза звучала,
  /// круг мог кончиться совсем — игрок ответил, ушёл с экрана, забег закрылся
  /// по сроку. Проверяется по **тому же объекту** вопроса: два круга по одной
  /// фразе — два разных вопроса, и окно второго не должно заводиться озвучкой
  /// первого.
  ///
  /// Ждать бесконечно нельзя, и этого не случится: у службы на одно
  /// произнесение стоит потолок (`DeviceSpeechService._speakCeiling`), а
  /// молчащее устройство отвечает сигналом сразу. Иначе круг со слухом на
  /// телефоне без голоса не открыл бы окно никогда — то есть повис бы.
  Future<void> _speakThenOpen(String text) async {
    final circle = state.current;
    final outcome = await ref.read(speechServiceProvider).speakAndWait(text);
    if (outcome != SpeechOutcome.done) return;
    if (_frozen ||
        state.phase != RunPhase.asking ||
        !identical(state.current, circle)) {
      return;
    }
    _openWindow();
  }

  /// Открывает окно на ответ: столько времени, сколько просит текст круга.
  ///
  /// Длину даёт [CircleQuestion.answerWindow] — там же, где записано и правило
  /// «на знакомстве окна нет». Здесь оно больше не повторяется: пока условие
  /// `question.isNew` жило и тут, у правила было две согласные копии, а копия,
  /// которую никто не сверяет, однажды перестаёт быть копией. Ровно так арена
  /// и разошлась с забегом в онбординге.
  void _openWindow() {
    _windowTimer?.cancel();
    final window = state.current?.answerWindow;
    if (window == null) {
      _showWindow(null);
      return;
    }
    // Таймер знает свою длину: она же уходит в журнал как время ответа, и
    // спрашивать её потом заново было бы вторым источником одного числа.
    _windowTimer = Timer(window, () => _expireWindow(window));
    _showWindow(window);
  }

  /// Снимает окно: ответ дан, круг ушёл или игрок ушёл с экрана.
  void _closeWindow() {
    _windowTimer?.cancel();
    _windowTimer = null;
    _showWindow(null);
  }

  /// Единственное место, которое пишет [RunState.window]: полоса окна и таймер
  /// обязаны появляться и исчезать вместе.
  void _showWindow(Duration? window) {
    if (state.window == window) return;
    state = state.copyWith(window: () => window);
  }

  /// Время вышло: круг закрывается неверным ответом.
  ///
  /// Просрочка — это «не вспомнил», а не отдельный третий исход. Слово
  /// тускнеет и возвращается в очередь ровно так же, как после промаха:
  /// не успел значит не вспомнил. Отличие одно — верный вариант при этом
  /// **произносится**, потому что промолчавшему игроку его никто не назвал.
  void _expireWindow(Duration window) {
    final question = state.current;
    if (question == null || state.phase != RunPhase.asking) return;
    // В журнал уходит длина окна: игрок думал ровно столько, сколько ему
    // дали, и запись об этом не должна выглядеть мгновенным ответом.
    _submit(question, false, window, expired: true);
  }

  void _submit(
    CircleQuestion question,
    bool correct,
    Duration latency, {
    bool expired = false,
  }) {
    _closeWindow();

    final result = _run.apply(
      correct: correct,
      latency: latency,
      mode: question.mode,
      lumens: question.lumens,
      replayed: _replayed,
    );

    // Каждое верное соединение озвучивается — во всех режимах, а не только
    // в «Слухе».
    //
    // `speakAndWait`, а не `speak`, и ждём мы не звука ради звука: конец
    // произнесения — это конец паузы ([_holdCircle]). Пока здесь стоял
    // `speak`, забег про свою озвучку не знал ничего, и круг закрывался по
    // числу — то есть поверх ещё звучащего ответа.
    final speech = ref.read(speechServiceProvider);
    Future<SpeechOutcome>? said;
    if ((correct || expired) && question.answerSpeech != null) {
      // По просрочке звучит верный вариант, и это не поблажка: игрок ничего
      // не выбрал, значит ему не сказали ответ ни выбором, ни подсветкой
      // выбранного.
      said = speech.speakAndWait(question.answerSpeech!);
    } else if (!correct) {
      speech.haptic();
    }

    // Память обновляется в фоне: диск между кругами игрок ждать не должен.
    // Уходит исходное время, а не приведённое: приводить его — работа домена,
    // а журнал отзывов хранит то, что было на самом деле.
    unawaited(_persist(question, correct, latency));

    final queue = List.of(state.queue);
    if (!correct) {
      // Слово возвращается в конец забега и теряет яркость.
      //
      // Другим экземпляром, и это не мелочь: арена сбрасывает состояние по
      // смене объекта вопроса. Пока за промахом стояли другие круги, разницы
      // не было — а когда промах последний, следующим показывался он же,
      // арена не сбрасывалась и переставала принимать ответы. Уровень висел.
      queue.add(question.again());
    }

    state = state.copyWith(
      queue: queue,
      phase: RunPhase.revealing,
      score: _run.score,
      combo: result.combo,
      correct: _run.correct,
      answered: state.answered + (correct ? 1 : 0),
      lastCorrect: () => correct,
    );

    unawaited(
      _holdCircle(
        question,
        said: said,
        floor: RevealBalance.forMode(question.mode, correct: correct),
      ),
    );
  }

  /// Держит круг открытым, пока ответ дозвучивает, и закрывает его сам.
  ///
  /// **Длину паузы задаёт озвучка, а не число.** Это и есть та жалоба,
  /// которую двумя заходами не удавалось закрыть: «слово обрывается на
  /// середине, а если следующее задание с динамиком, то сразу звучит новое».
  /// Число тут не подходит по построению — сколько звучит фраза, знает
  /// устройство, а не баланс: голос чужой, скорость своя, длина фразы от A0 до
  /// B2 разная втрое.
  ///
  /// Краёв у ожидания три, и каждый закрывает свою дыру.
  ///
  /// * **Низ** ([floor], `RevealBalance`) — на случай «говорить нечем»: звук
  ///   выключен, голоса нет, текста нет, и `done` приходит сразу. Без низа
  ///   круг мигнул бы мимо глаз, а на промахе это значило бы, что верный
  ///   вариант не увидел никто. Идёт он **параллельно** ожиданию, а не после
  ///   него: пауза кончается, когда прошло и то, и другое, — то есть на
  ///   говорящем устройстве низ не прибавляется к озвучке, а прячется внутри
  ///   неё.
  /// * **Верх** ([RevealBalance.ceiling]) — на случай платформы, которая не
  ///   отвечает. Забег не вправе зависеть от того, дойдёт ли до него чужой
  ///   сигнал: круг обязан закрыться, даже если сигнала не будет никогда.
  /// * **Вытеснение** ([SpeechOutcome.displaced]) — «моего произнесения
  ///   больше нет»: его оборвал `stop`, вытеснил новый запрос или служба
  ///   замолчала (уход с экрана запирает голос в корне приложения). Ждать
  ///   его нельзя вовсе — оно не кончится ничем, — и пауза оседает на низ.
  ///   Оба исхода поэтому кончают ожидание, и различать их незачем: разница
  ///   между «дозвучало» и «дозвучать не сможет» для паузы одна — ждать
  ///   больше нечего.
  ///
  /// Закрывает круг сама пауза, но проверяет перед этим, тот ли круг ещё
  /// стоит ([_holdsCircle]): за время ожидания игрок мог закрыть паузу
  /// досрочно ([skipReveal]), забег мог замереть ([freeze]) или кончиться
  /// совсем.
  Future<void> _holdCircle(
    CircleQuestion circle, {
    required Future<SpeechOutcome>? said,
    required Duration floor,
  }) async {
    _revealTimer?.cancel();
    final low = Completer<void>();
    _revealTimer = Timer(floor, low.complete);
    if (said != null) {
      await said.timeout(
        RevealBalance.ceiling,
        onTimeout: () => SpeechOutcome.displaced,
      );
    }
    await low.future;
    if (!_holdsCircle(circle)) return;
    _advance();
  }

  /// Стоит ли [circle] всё ещё открытым в паузе — той самой, которая ждёт.
  ///
  /// Сверяется **тот же объект** вопроса, а не идентификатор фразы: два круга
  /// по одной фразе — два разных вопроса (`CircleQuestion.again`), и пауза
  /// первого не вправе закрыть второй.
  bool _holdsCircle(CircleQuestion circle) =>
      !_frozen &&
      state.phase == RunPhase.revealing &&
      identical(state.current, circle);

  /// Закрывает паузу досрочно: нажатие по арене.
  ///
  /// Ждать не обязан тот, кто уже всё прочёл и услышал, — правило это старше
  /// автоперехода и переживает его во второй раз. Пропустить круг оно при этом
  /// не позволяет: до ответа нажатие не делает ничего, иначе игрок,
  /// промахнувшийся мимо варианта, терял бы вопрос вместе с яркостью фразы.
  ///
  /// **Кнопки «Дальше» больше нет, и это отмена прошлого захода.** Она стояла
  /// под ареной и была единственным, что тогда давало верному ответу
  /// дозвучать: пауза до неё была числом (420/1100 мс), в которое озвучка не
  /// укладывалась. Стоило это касания на каждом из десяти-четырнадцати кругов
  /// забега. Теперь дозвучать даёт сама пауза ([_holdCircle]), а нажатие снова
  /// стало тем, чем было, — досрочным.
  ///
  /// **У спринта пауза та же.** Часы там идут независимо от игрока — срок
  /// поставлен в момент старта и в связях не считается, — поэтому пауза тратит
  /// его собственное время. Спринтеру это цена звука, и снять её нельзя,
  /// не отняв у него озвучку: сокращать паузу только в спринте означало бы два
  /// разных правила темпа на одном экране, а закрывать её досрочно он и так
  /// вправе — этим самым нажатием.
  void skipReveal() {
    if (state.phase != RunPhase.revealing) return;
    _advance();
  }

  void _advance() {
    // Пауза кончилась — чем бы её ни кончили. Отменённый низ не даёт
    // ожиданию досчитать, и круг не закроется дважды: сперва досрочным
    // нажатием, потом дозвучавшим ответом.
    _revealTimer?.cancel();
    // Спринт кончается на достигнутой планке, а не на конце очереди:
    // считаются верные связи. Иначе ошибка, возвращающая круг в конец
    // очереди, продлевала бы забег — то есть наказание за промах
    // превращалось бы в лишнее время.
    if (state.goalReached) {
      _finish();
      return;
    }

    final next = state.index + 1;
    if (next >= state.queue.length || _isOutOfTime) {
      _finish();
      return;
    }
    _replayed = false;
    state = state.copyWith(
      index: next,
      phase: RunPhase.asking,
      lastCorrect: () => null,
    );
    _beginCircle();
  }

  /// Время Восхода вышло. Проверяется между кругами, а не по таймеру:
  /// прерывать открытый круг нельзя.
  bool get _isOutOfTime {
    final deadline = _deadline;
    return deadline != null && DateTime.now().isAfter(deadline);
  }

  /// Прогревает синтез между кругами.
  ///
  /// Предзагрузки у синтеза нет — открывать нечего. Но есть платформенный
  /// вызов состояния и ленивая настройка движка, и оба лучше сделать
  /// заранее, чем в момент касания.
  void _preloadNext() {
    unawaited(ref.read(speechServiceProvider).status());
  }

  /// Проигрывает центр заново по нажатию на динамик.
  ///
  /// Переслушивание разрешено, но снимает скоростной множитель — иначе
  /// «Слух» превращался бы в «Круг» с лишним тапом.
  ///
  /// Окно при этом **перезапускается**: на время повтора его нет вовсе (пока
  /// фраза звучит, отвечать не на что), а после — заводится с полного времени.
  /// Часы, идущие сквозь повтор, были бы платой за чужую медлительность:
  /// игрок попросил повторить, а не отказался от половины своего окна. Цену
  /// переслушивания берёт скоростной множитель, а не отобранные секунды.
  void replayPrompt() {
    final text = state.current?.promptSpeech;
    if (text == null || state.phase != RunPhase.asking) return;
    _replayed = true;
    _closeWindow();
    unawaited(_speakThenOpen(text));
  }

  /// Переслушивал ли игрок центр на текущем круге.
  ///
  /// Сбрасывается при переходе к следующему кругу, а не при ответе: между
  /// ответом и переходом круг нажатий уже не принимает ([replayPrompt] требует
  /// [RunPhase.asking]), и переслушать в этот зазор нечего. С заморозкой
  /// забега ([freeze]) это никак не связано: там останавливается весь забег,
  /// а здесь просто кончился приём ответа.
  bool _replayed = false;

  // ── Заморозка: экран, фон и вопрос о прерывании ──────────────────────────

  void _screenChanged(AppLifecycleState state) {
    // На экране — только `resumed`. Всё остальное, включая `inactive`
    // (входящий звонок, шторка уведомлений, окно без фокуса на десктопе), —
    // это «игрок не смотрит»: ответить он не может, а значит и торопить его
    // нельзя.
    if (state == AppLifecycleState.resumed) {
      unfreeze();
    } else {
      freeze();
    }
  }

  /// Игрока перед кругом нет: забег замирает целиком.
  ///
  /// **Имя больше не про экран, и это исправленная ложь, а не вкус.** Метод
  /// звался `leaveScreen`, потому что причина была одна — приложение ушло с
  /// экрана. Причин стало две, и вторая происходит на том же самом экране:
  /// вопрос «точно прервать ритуал?» закрывает круг собой
  /// (`RitualScreen`), и отвечать игроку в этот момент так же нечем, как в
  /// закрытом окне. Второго механизма для неё нет намеренно — забегу от обеих
  /// причин нужно ровно одно и то же (не тратить окно, не считать просрочку,
  /// не двигать срок, а на возвращении открыть окно заново), и появись второй
  /// путь, эти четыре правила пришлось бы держать согласованными в двух
  /// местах. Что именно забрало у игрока круг, забег знать не обязан.
  ///
  /// Что было без этого — жалоба владельца дословно: «когда я закрыл окно с
  /// игрой — она продолжает работать в фоне — я слышу текст». Игра не
  /// доигрывала звук, она **продолжала играть сама**: окно ответа истекало по
  /// таймеру, просрочка уходила в память ответом «не вспомнил», звучал верный
  /// вариант, срабатывал автопереход, новый круг произносил свой вопрос и
  /// открывал новое окно. Игрок слышал не остаток фразы, а забег, который шёл
  /// без него и тратил его звёзды: каждая просрочка роняла яркость и
  /// отправляла фразу в конец очереди.
  ///
  /// Останавливаются здесь **таймеры**, потому что они принадлежат забегу.
  /// Голос принадлежит приложению — он один на забег и калибровку, — и запирает
  /// его корень (`SilenceOffScreen` в `main.dart`), а держит запертым сама
  /// служба. Забегу поэтому нечего делать с голосом даже здесь: попросить его
  /// замолчать он не может забыть, потому что и не просит.
  ///
  /// Голос это и объясняет, почему вопрос о прерывании звук не запирает: на
  /// экране приложение осталось, и оборванная на полуслове фраза была бы
  /// платой за один тап по крестику. Диалог отбирает у игрока **круг**, а не
  /// приложение, и забирает поэтому только таймеры.
  void freeze() {
    if (_frozen) return;
    _frozen = true;
    _frozenAt = DateTime.now();
    _closeWindow();
    // Пауза — такой же отсчёт круга, как окно, и замороженной ей идти нельзя.
    // Иначе вернулась бы вся та петля целиком: пауза дотикала бы в закрытом
    // окне, открыла следующий круг, тот произнёс бы свой вопрос и завёл своё
    // окно.
    _revealTimer?.cancel();
  }

  /// Игрок вернулся к кругу: он открывается заново, а не с остатка.
  ///
  /// С остатка было бы наказанием за то, чего игрок не видел: ни фразы, ни
  /// полосы, ни того, сколько времени уже съедено. Поэтому окно открывается с
  /// полного времени, а круг на слух заново произносит центр — и это не
  /// считается переслушиванием: звук отобрала игра, а не игрок попросил
  /// повторить.
  ///
  /// **Пауза после ответа тоже начинается заново, но без озвучки.** Ждать ей
  /// нечего: произнесение ответа оборвал корень приложения вместе с уходом
  /// (`SilenceOffScreen`), то есть оно вытеснено и не кончится ничем. После
  /// вопроса о прерывании оно, наоборот, могло дозвучать целиком — голос там
  /// никто не запирал, — и низ паузы тогда просто отмерит круг ещё раз: лишние
  /// полсекунды на месте, где игрок только что читал текст диалога, дешевле
  /// второго правила про то, чем кончилась заморозка. Читать
  /// ответ заново забег при этом не берётся, и это решение, а не упущение:
  /// игрок этот вариант сам выбрал и видит подсвеченным, а фраза, прозвучавшая
  /// через минуту после возвращения, — тот же голос из закрытого окна, только
  /// с опозданием (ровно то, чего служба не делает нарочно, см.
  /// `SpeechService.silence`). Круг поэтому доживает свой низ и уходит.
  ///
  /// Срок забега сдвигается на время заморозки. Оно забегу не принадлежит — ни
  /// его срок, ни его длительность, — иначе спринт, чьи часы идут независимо
  /// от игрока, умирал бы от входящего звонка или от прочитанного вопроса, а
  /// Восход заканчивался бы, ни разу не показав круг.
  void unfreeze() {
    if (!_frozen) return;
    _frozen = false;
    final left = _frozenAt;
    if (left != null) {
      final away = DateTime.now().difference(left);
      _deadline = _deadline?.add(away);
      _startedAt = _startedAt.add(away);
    }
    _frozenAt = null;
    final circle = state.current;
    if (state.phase == RunPhase.asking) {
      _beginCircle();
    } else if (state.phase == RunPhase.revealing && circle != null) {
      unawaited(
        _holdCircle(
          circle,
          said: null,
          floor: RevealBalance.forMode(
            circle.mode,
            correct: state.lastCorrect ?? false,
          ),
        ),
      );
    }
  }

  void _finish() {
    _closeWindow();
    // Забег кончился — паузе закрывать больше нечего.
    _revealTimer?.cancel();
    final summary = _run.summary();
    state = state.copyWith(
      phase: RunPhase.finished,
      summary: summary,
      lastCorrect: () => null,
    );
    ref.read(analyticsProvider).log(AnalyticsEvents.runFinished, {
      'score': summary.total,
      'accuracy': summary.accuracy,
      'max_combo': summary.maxCombo,
    });
  }

  Future<void> _persist(
    CircleQuestion question,
    bool correct,
    Duration latency,
  ) async {
    try {
      final now = DateTime.now();
      final update =
          await ref.read(wordStateRepositoryProvider).applyAnswer(
                itemId: question.itemId,
                tier: question.tier,
                mode: question.mode,
                correct: correct,
                latency: latency,
                now: now,
              );

      final gained = update.lumensGained(now);
      if (gained > 0) _lmGained += gained;

      // Сообщаем только о моменте зажигания, а не о каждом быстром ответе
      // на уже горящем слове.
      if (update.justIgnited) {
        ref.read(analyticsProvider).log(AnalyticsEvents.wordBurning, {
          'concept': question.itemId,
        });
      }
    } catch (_) {
      // База недоступна — забег важнее прогресса. Потерянный ответ хуже,
      // чем прерванная игра, но ненамного: следующий круг всё исправит.
    }
  }

  int _lmGained = 0;

  /// Сколько люменов вернулось небу за забег — это и есть основа рейтинга
  /// лиг (M6): фармить повтором лёгкого его нельзя.
  int get lumensGained => _lmGained;
}

final runControllerProvider =
    NotifierProvider<RunController, RunState>(RunController.new);
