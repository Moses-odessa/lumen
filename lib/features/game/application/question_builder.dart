/// Собирает круг из контента: что в центре, что вокруг, что верно.
///
/// Единица изучения — фраза, и вариантов в круге всегда шесть: сама фраза и
/// пять других. Откуда берутся эти пять — решают двое, и разделение не
/// формальное.
///
/// **Загрузчик знает память.** Он передаёт пул и две метки: какие фразы игрок
/// уже знает (`known`) и какие хотя бы видел (`seen`). Знакомство устроено
/// методом исключения — игрок понимает, какая из шести фраз новая, потому что
/// остальные пять узнаёт, — а это правило про память, и жить оно должно там,
/// где память есть.
///
/// **Сборщик знает оба языка круга и верный ответ.** Внутри полосы памяти он
/// берёт не первые попавшиеся, а те фразы, что **максимально совпадают
/// словами с ответом**. Круг из шести непохожих фраз решается по одному
/// знакомому слову, и игрок учится узнавать не фразу, а случайную примету.
/// Когда вокруг стоят фразы из тех же слов, отличить их можно только прочитав
/// целиком — то есть ровно тем усилием, которое и есть учение. Считать это
/// может только тот, кто знает, на каком языке варианты показаны и какой из
/// них верный.
///
/// Языков у круга два, и путать их нельзя: похожесть считается на языке
/// **вариантов** (его игрок читает в плитках), а двусмысленность — на языке
/// **центра** (он задаёт вопрос). См. [_pickOthers].
///
/// Раньше пул приходил одним упорядоченным списком, и сборщик брал первые
/// пять: порядок выражал память, а совпадение слов не выражал никто.
///
/// Возвращает `null`, если круг собрать нельзя: у фразы нет перевода на
/// родной язык или в пуле не набралось пяти других фраз. Молча показать
/// сломанный круг хуже, чем пропустить фразу.
class QuestionBuilder {
  QuestionBuilder({
    required this.content,
    required this.targetLang,
    required this.nativeLang,
    Random? random,
  }) : _random = random ?? Random();

  final ContentDatabase content;

  /// Язык изучения — на нём написаны фразы.
  final String targetLang;

  /// Язык подсказок — на нём переводы.
  final String nativeLang;

  final Random _random;

  /// Корпус на каждом из двух языков, прочитанный по первому требованию.
  ///
  /// Хранится **future**, а не результат: два круга подряд не должны
  /// прочитать таблицу дважды только потому, что первый ещё не дочитал.
  Future<_Corpus>? _target;
  Future<_Corpus>? _native;

  /// Собирает круг по запланированной фразе.
  ///
  /// [pool] — идентификаторы фраз, из которых берутся пять других вариантов.
  /// Сама фраза круга из пула отбрасывается, так что передавать его
  /// отфильтрованным не нужно.
  ///
  /// [known] — те из них, которые игрок знает достаточно, чтобы узнать в
  /// круге; [seen] — те, которые он хотя бы видел. Второе шире первого:
  /// фраза, которую игрок видел и забыл, пройдена, но узнать её он не может.
  /// Обе метки по умолчанию пусты, и это осмысленное значение, а не заглушка:
  /// у нового игрока и на калибровке пройденного нет вовсе, и круг обязан
  /// собираться всё равно.
  Future<CircleQuestion?> build(
    PlannedCircle circle, {
    required List<String> pool,
    Set<String> known = const {},
    Set<String> seen = const {},
  }) async {
    final phrase = await content.phrase(circle.itemId);
    if (phrase == null) return null;

    final inTarget = await _targetCorpus();
    final inNative = await _nativeCorpus();
    final onTarget = circle.mode.optionsInTargetLanguage;
    final shown = onTarget ? inTarget : inNative;
    // Язык центра — всегда тот, которого нет в вариантах: `pickNative` и
    // `listenNative` ставят в центр изучаемую фразу (во второй — звучащую) и
    // раскладывают вокруг переводы, `pickTarget` делает наоборот. Круг, у
    // которого центр и варианты на одном языке, был бы кругом без задания,
    // поэтому отрицание здесь не сокращение, а само устройство механик —
    // сторожится в `session_planner_test.dart`.
    final centre = onTarget ? inNative : inTarget;

    // Перевод нужен и центру, и каждому варианту: на родном языке стоят либо
    // варианты, либо центр. Фраза без перевода круг не собирает — ни своим,
    // ни чужим. У вариантов это правило работает отбором (кандидат без
    // перевода в пятёрку не идёт), у самой фразы — отказом: подменить её
    // нечем.
    final answer = shown.shapes[circle.itemId];
    // Тот же ответ, прочитанный на языке центра: он и есть текст вопроса.
    final centreAnswer = centre.shapes[circle.itemId];
    final answerNative = inNative.texts[circle.itemId];
    if (answer == null || centreAnswer == null || answerNative == null) {
      return null;
    }

    final others = _pickOthers(
      circle.itemId,
      answer: answer,
      centreAnswer: centreAnswer,
      pool: pool,
      shown: shown,
      centre: centre,
      known: known,
      seen: seen,
    );
    if (others.length < ScoreBalance.optionsPerCircle - 1) return null;

    final ids = [circle.itemId, ...others];
    // Текст ответа берётся из строки фразы, а не из корпуса: строка —
    // источник, корпус — её копия для сравнений.
    final answerTarget = phrase.sentence;
    final options = [
      for (final id in ids)
        onTarget
            ? (id == circle.itemId ? answerTarget : inTarget.texts[id]!)
            : inNative.texts[id]!,
    ];

    // Порядок вариантов перемешивается, иначе верный всегда стоит первым.
    final order = List<int>.generate(options.length, (i) => i)
      ..shuffle(_random);
    final shuffled = [for (final i in order) options[i]];
    final answerIndex = order.indexOf(0);

    return CircleQuestion(
      itemId: circle.itemId,
      tier: Tier.fromCode(phrase.tier),
      mode: circle.mode,
      // В механике на слух центр пуст: его занимает динамик.
      prompt: switch (circle.mode) {
        GameMode.pickNative => answerTarget,
        GameMode.pickTarget => answerNative,
        GameMode.listenNative => '',
      },
      promptTag: phrase.register,
      options: shuffled,
      answerIndex: answerIndex,
      lumens: circle.lumens,
      isNew: circle.isNew,
      promptSpeech: circle.mode.needsAudio ? answerTarget : null,
      answerSpeech: answerTarget,
      // Перевод показывается вместе с ответом — но только там, где он не
      // является самим ответом. В `pickNative` вокруг стоят переводы, и
      // показать его второй раз значит сказать игроку то, что он и выбрал.
      translation: circle.mode == GameMode.pickNative ? null : answerNative,
    );
  }

  /// Пять других фраз круга: полосами памяти, внутри полосы — по совпадению
  /// слов с верным ответом.
  ///
  /// **Полос три, потому что правил два.** Знакомство исключением требует,
  /// чтобы вокруг новой фразы стояли **известные**: не узнав пять, шестую не
  /// исключишь. Правило владельца требует, чтобы варианты были уже
  /// **пройденными**: круг из незнакомого не спрашивает, а гадает. Пройденное
  /// шире известного — фраза, которую игрок видел и забыл, пройдена, но
  /// узнать её он не может, — поэтому полосы идут по убыванию памяти:
  /// известные, потом просто виденные, потом невиданные фразы яруса. Каждое
  /// правило остаётся целым, и ни одно не отменяет другое.
  ///
  /// **Внутри полосы порядок задаёт совпадение слов, а не яркость.** Полоса
  /// уже сказала «этого хватит, чтобы узнать»; выбирать внутри неё осмысленно
  /// по трудности. Яркость осталась разрешением ничьих: пул приходит от
  /// загрузчика отсортированным по ней, и при равной похожести раньше стоит
  /// то, что ярче — а раньше стоящий скорее попадёт в добор и переживёт
  /// отсев одинаковых текстов.
  ///
  /// **Двух верных ответов не бывает, и считаются они на языке центра.**
  /// Кандидат негоден, если текст центра описывает и его: см.
  /// [ShownPhrase.describes]. Язык здесь именно центра, а не вариантов —
  /// вопрос задаёт центр, и два варианта верны одновременно тогда, когда его
  /// текст подходит обоим.
  ///
  /// **Сегодня эта проверка не отвергает ничего, и написана она ровно
  /// поэтому.** Корпус вырос до 1500 фраз и потерял многоточия («с ним не
  /// понятно как читать»), а без места под своё слово описание сводится к
  /// равенству текстов — и одинаковых текстов в корпусе тоже ноль, ни в
  /// одном из двух языков. Замерено на отгруженном ассете: 0 многоточий, 0
  /// пар «центр описывает чужую фразу» — и с центром на изучаемом, и с
  /// центром на родном. Это **ограждение**, а не лечение: форма с
  /// многоточием законна и возвращается одной правкой листа, а пару
  /// одинаковых переводов даст первая же добавленная тема. Снять проверку как
  /// «защищающую от несуществующего» значит вернуть круг, где игрок нажимает
  /// верное и получает «неверно».
  ///
  /// Лечением она была в прежней тысяче фраз, и там же был найден дефект:
  /// проверка стояла на противоположном языке и пропускала ровно те круги,
  /// которые обязана была ловить. В `pickTarget` на центре «Де ...?» девять
  /// из дюжины кандидатов были законными ответами — «Wo wohnst du?», «Wo
  /// arbeitest du?», — а фильтр сверял немецкий, где «Wo ist ...?» их не
  /// покрывает. Направление и язык сторожатся тремя тестами на самодельном
  /// корпусе (`session_loader_test.dart`): материала для них в ассете больше
  /// нет, а на ассете правило проверить нечем — сплошной проход по нему
  /// зеленеет и с удалённой проверкой.
  ///
  /// **Двух одинаковых плиток не бывает, и считаются они на языке
  /// вариантов.** Это другой дефект и другой язык: одинаковый показанный
  /// текст круг принял бы обоими нажатиями ([CircleQuestion.isCorrectOption]
  /// сверяет текст). Сравниваются не только с ответом, но и кандидаты между
  /// собой: у одинаковых текстов похожесть максимальна, и в отсортированной
  /// полосе они встали бы рядом. Пар с одинаковым текстом в корпусе тоже
  /// ноль — на 1500 фразах, в каждом из пяти языков, — и это второе
  /// ограждение: перевод пишет человек.
  ///
  /// **Похожих выбирает порог, а не счётчик.** Похожим считается кандидат не
  /// хуже [ScoreBalance.confusableShare] от лучшего в полосе и не ниже
  /// [ScoreBalance.confusableFloor]; из похожих пятёрка **жеребится**, иначе
  /// круг повторялся бы из забега в забег и игрок запомнил бы расположение, а
  /// не фразы.
  ///
  /// Прежде на этом месте стояло окно на дюжину, и оно молчало там, где
  /// нужнее всего: пока пройденных меньше дюжины, окно накрывало всю полосу,
  /// жеребьёвка становилась равномерной по всему пройденному и ранжирование
  /// не влияло ни на что. Это не оценка, а арифметика — одиннадцать
  /// кандидатов при окне на двенадцать, — и измерена она на настоящем
  /// сборщике: на полосе из первой дюжины A0 окно давало похожесть 0.0731,
  /// то есть в точности среднюю по всей полосе, а порог даёт 0.1552 — вдвое
  /// больше. На полном пуле из 1500 фраз разрыв всего 3–4 %: там и первая
  /// дюжина почти вся похожа. Оба числа сторожатся тестами.
  ///
  /// **Недостача добирается следующими по похожести.** Похожих может не
  /// оказаться и пяти — правило улучшает круг, а не запрещает его, поэтому
  /// круг собирается всё равно: четыре похожих и один любой лучше пяти любых.
  /// Добор идёт жеребьёвкой из следующих по похожести, числом на круг: брать
  /// строго лучшего значило бы, что такой круг повторяется дословно.
  ///
  /// Точное обещание поэтому такое: **каждый вариант либо похож по порогу,
  /// либо стоит сразу за похожими** — и не «пятёрка из дюжины самых похожих»,
  /// как здесь было написано, пока дюжина была счётчиком.
  ///
  /// **На первом уровне пройденного нет вовсе**, и это не поломка: две первые
  /// полосы пусты, третья — весь ярус, и первый круг честно оказывается
  /// выбором из шести незнакомых. Дальше полосы наполняются сами.
  List<String> _pickOthers(
    String itemId, {
    required ShownPhrase answer,
    required ShownPhrase centreAnswer,
    required List<String> pool,
    required _Corpus shown,
    required _Corpus centre,
    required Set<String> known,
    required Set<String> seen,
  }) {
    final bands = <List<_Candidate>>[[], [], []];
    final used = {itemId};
    // Показанные тексты круга, и начинается набор с ответа: плитка, равная
    // ответу, — это две верных плитки, а равная другой плитке — две
    // одинаковых. Множество растёт кандидатами, поэтому сверка идёт и между
    // ними, а не только с ответом.
    final texts = {answer.key};
    for (var order = 0; order < pool.length; order++) {
      final id = pool[order];
      if (!used.add(id)) continue;

      final shape = shown.shapes[id];
      final asked = centre.shapes[id];
      // Кандидат, у которого нет текста на одном из двух языков круга, в него
      // не идёт: неполный язык обязан давать меньше вариантов, а не чужие.
      // Языка два, потому что проверок две — по одной на каждый.
      if (shape == null || asked == null) continue;
      // Второй верный ответ — на языке **центра**: вопрос задаёт центр, и
      // верны оба варианта тогда, когда его текст описывает оба.
      if (centreAnswer.describes(asked)) continue;
      // Вторая одинаковая плитка — на языке **вариантов**: его игрок читает, и
      // круг принимает текст, а не номер. Дефект другой, язык другой.
      if (!texts.add(shape.key)) continue;

      final band = known.contains(id) ? 0 : (seen.contains(id) ? 1 : 2);
      bands[band].add((
        id: id,
        overlap: answer.overlapWith(shape),
        order: order,
      ));
    }

    final need = ScoreBalance.optionsPerCircle - 1;
    final picked = <String>[];
    for (final band in bands) {
      if (picked.length == need) break;
      band.sort((a, b) {
        final byOverlap = b.overlap.compareTo(a.overlap);
        return byOverlap != 0 ? byOverlap : a.order.compareTo(b.order);
      });

      // Порог считается **до** жеребьёвки и по лучшему в полосе, а не
      // пересчитывается на каждом шаге: иначе после четырёх изъятий он
      // сползал бы вслед за остатком, и «похожий» означало бы «похожий на то,
      // что осталось».
      final bar = _confusableBar(band);
      final similar = band.where((c) => c.overlap >= bar).toList();
      while (picked.length < need && similar.isNotEmpty) {
        picked.add(similar.removeAt(_random.nextInt(similar.length)).id);
      }
      if (picked.length == need) continue;

      // Добор: следующие по похожести, числом ровно на круг. Пять — не
      // отдельное число, а те же пять других вариантов: меньше не даст
      // жеребьёвке выбора, больше уведёт в шум.
      final next = band.where((c) => c.overlap < bar).take(need).toList();
      while (picked.length < need && next.isNotEmpty) {
        picked.add(next.removeAt(_random.nextInt(next.length)).id);
      }
    }
    return picked;
  }

  /// Мера, начиная с которой кандидат полосы считается похожим.
  ///
  /// Полоса приходит отсортированной, поэтому лучший — первый. Ниже
  /// [ScoreBalance.confusableFloor] похожести нет вовсе: если и лучший
  /// кандидат ниже дна, порога нет (ноль), и пятёрка жеребится по всей полосе.
  /// Так круг собирается даже там, где похожих не существует.
  static double _confusableBar(List<_Candidate> band) {
    if (band.isEmpty) return 0;
    final best = band.first.overlap;
    if (best < ScoreBalance.confusableFloor) return 0;
    return max(
      ScoreBalance.confusableFloor,
      best * ScoreBalance.confusableShare,
    );
  }

  Future<_Corpus> _targetCorpus() => _target ??= _loadTarget();
  Future<_Corpus> _nativeCorpus() => _native ??= _loadNative();

  Future<_Corpus> _loadTarget() async {
    // Читается вся таблица, а не ярус игрока: какие фразы попадут в пул,
    // решает загрузчик, а мера похожести требует текст **каждого** кандидата,
    // а не только пяти выбранных. Спрашивать по одному идентификатору значило
    // бы сотню запросов на круг.
    final rows = await content.phrasesUpTo(Tier.values.last);
    return _Corpus(
      {for (final row in rows) row.id: row.sentence},
      {for (final row in rows) row.id: ShownPhrase.of(row.sentence)},
    );
  }

  Future<_Corpus> _loadNative() async {
    final ids = (await _targetCorpus()).texts.keys.toList();
    final texts = <String, String>{};
    // Переводы спрашиваются пачками: `IN (...)` на тысячу идентификаторов
    // упирается в ограничение SQLite на число параметров запроса, и падение
    // выглядело бы как сессия без единого круга.
    for (var i = 0; i < ids.length; i += _idsPerQuery) {
      final chunk = ids.sublist(i, min(i + _idsPerQuery, ids.length));
      texts.addAll(await content.translationsFor(chunk, nativeLang));
    }
    return _Corpus(
      texts,
      {
        for (final entry in texts.entries)
          entry.key: ShownPhrase.of(entry.value),
      },
    );
  }

  /// Сколько идентификаторов уходит в один запрос. Не игровое число, а предел
  /// SQLite (999 параметров по умолчанию), поэтому живёт здесь, а не в
  /// `balance.dart`.
  static const int _idsPerQuery = 400;
}

/// Кандидат в варианты: чем он похож на ответ и где стоял в пуле.
///
/// Порядок в пуле хранится затем, чтобы сортировка была воспроизводимой:
/// `List.sort` в Dart не стабилен, и без явного разрешения ничьих два
/// одинаково похожих кандидата вставали бы в круг по-разному от запуска к
/// запуску — то есть тест на зерно перестал бы значить хоть что-нибудь.
typedef _Candidate = ({String id, double overlap, int order});

/// Тексты одного языка целиком, разобранные для сравнения.
///
/// Читается один раз за жизнь сборщика и держится в памяти. Контентная база
/// read-only, поэтому прочитанное не устаревает, а тысяча коротких строк —
/// это десятки килобайт против сотни запросов на каждый круг.
class _Corpus {
  const _Corpus(this.texts, this.shapes);

  /// `id → текст, как он будет показан`.
  final Map<String, String> texts;

  /// `id → разбор того же текста`.
  final Map<String, ShownPhrase> shapes;
}

/// Текст варианта в том виде, в котором его читает игрок: слова без регистра
/// и знаков плюс места, оставленные под своё слово.
///
/// Нужен затем, чтобы измерить, насколько два варианта круга похожи. Мера
/// считается **по языку показа**: `pickNative` и `listenNative` показывают
/// переводы, `pickTarget` — фразы изучаемого языка. Мерить похожесть на другом
/// языке значило бы мерить не то, что игрок читает.
///
/// Нормализация — три вещи, и каждая нужна.
///
/// * **Регистр.** «Ich» в начале фразы и «ich» в середине — одно слово; в
///   круге они стоят как написаны, а сравниваются как одно.
/// * **Знаки.** Точка, запятая и вопросительный знак слова не меняют. Апостроф
///   и дефис внутри слова — часть слова: «l'acqua» и «E-Mail» это по одному
///   слову, а не по два.
/// * **Многоточие.** Это не знак, а место под своё слово: «Ich brauche ...» —
///   шаблон. Слова оно не даёт, но и бесследно не исчезает: по нему видно, не
///   заполняется ли шаблон готовой фразой целиком (см. [describes]).
///
///   В сегодняшнем корпусе многоточий **ноль** — в прежней тысяче фраз их
///   было 239, и на их место встали «примеры»: законченные образцы речевой
///   модели, «Ich heiße Alex.» вместо «Ich heiße ...» (`phrases.kind`, схема
///   v7). Разбор дыр оставлен дремлющим, а не удалён: форма законна,
///   возвращается одной правкой листа контента, и без неё круг с шаблоном в
///   центре снова получит два верных ответа. Ровно так же помечена
///   маскировка многоточия в `tool/validate_content.dart` — без неё проверка
///   «фраза это одно предложение» давала 84 ложных отказа.
class ShownPhrase {
  const ShownPhrase._(this.segments, this.words, this.key);

  /// Разбирает показанный текст.
  factory ShownPhrase.of(String raw) {
    final segments = <List<String>>[];
    for (final part in raw.toLowerCase().split(_holes)) {
      final words = <String>[];
      for (final piece in part.split(_notWord)) {
        final word = piece.replaceAll(_edges, '');
        if (word.isNotEmpty) words.add(word);
      }
      segments.add(words);
    }
    final words = [for (final segment in segments) ...segment];
    return ShownPhrase._(segments, words, words.join(' '));
  }

  /// Слова между дырами: по списку на отрезок. Отрезков ровно на один больше,
  /// чем дыр, а пустой отрезок означает дыру в начале или в конце.
  final List<List<String>> segments;

  /// Все слова подряд, без дыр.
  final List<String> words;

  /// Нормализованный текст: слова через пробел. По нему сравнивается «это тот
  /// же самый показанный текст» — а два одинаковых показанных текста в одном
  /// круге это две плитки, каждую из которых круг примет верной. Поэтому
  /// сборщик держит ключи выбранных вариантов множеством: сравнение идёт и с
  /// ответом, и между кандидатами.
  final String key;

  /// Есть ли в тексте место под своё слово.
  bool get hasHole => segments.length > 1;

  /// Насколько [other] похож на этот текст. Больше — путает сильнее.
  ///
  /// Слагаемых два, и каждое отвечает за свою ошибку.
  ///
  /// **Жаккар** — доля общих слов в объединении. Простое пересечение множеств
  /// благоволило бы длинным фразам: у фразы из двенадцати слов общих слов с
  /// чем угодно больше, чем у фразы из трёх, и вокруг короткого ответа встало
  /// бы пять длинных — то есть пять заведомо неверных. Жаккар нормирует:
  /// «Ich weiß nicht.» ближе к «Ich verstehe nicht.», чем к «Ich möchte
  /// wissen, wie meine Daten verwendet werden.», хотя общих слов у второй
  /// пары не меньше.
  ///
  /// **Совпадение начала** — доля общего начала в более короткой из двух
  /// фраз. Начало путает сильнее всего: «Ich brauche Hilfe.» против «Ich
  /// brauche einen Stift.» читается одинаково, пока не дочитаешь до конца, и
  /// это дочитывание и есть учение. Множествам порядок безразличен, поэтому
  /// без второго слагаемого одинаковое начало ничем не отличалось бы от
  /// одинакового конца.
  ///
  /// Пара взята из корпуса, и взята не случайно: `needs_help_a0_18` — та
  /// самая строка, где прежде стоял шаблон «Ich brauche ...». Многоточия
  /// ушли, и место шаблона занял законченный пример; путаницу начала это не
  /// убрало, а сделало обычным делом — теперь она между двумя целыми
  /// фразами.
  ///
  /// Вес второго слагаемого — [ScoreBalance.confusablePrefixWeight]; сумма
  /// лежит между 0 и 1 + вес.
  double overlapWith(ShownPhrase other) {
    if (words.isEmpty || other.words.isEmpty) return 0;

    final mine = words.toSet();
    final theirs = other.words.toSet();
    final shared = mine.intersection(theirs).length;
    final jaccard = shared / (mine.length + theirs.length - shared);

    final limit = min(words.length, other.words.length);
    var prefix = 0;
    while (prefix < limit && words[prefix] == other.words[prefix]) {
      prefix++;
    }

    return jaccard +
        ScoreBalance.confusablePrefixWeight * (prefix / limit);
  }

  /// Описывает ли этот текст — текст **центра** — ещё и фразу [other], то
  /// есть верны ли в круге оба варианта сразу.
  ///
  /// Двух верных ответов быть не может: игрок выбирает вариант, а круг
  /// принимает **текст** ([CircleQuestion.isCorrectOption]), и «неверно» на
  /// верном ответе игрок получает по чужой вине. Правило «варианты
  /// максимально совпадают с ответом» ведёт прямо к этому обрыву — оно
  /// поднимает наверх ровно те пары, которые различить нельзя.
  ///
  /// Описанием считаются два случая.
  ///
  /// * **Тот же текст** с точностью до регистра и знаков. Таких пар в корпусе
  ///   нет ни в одном языке — ноль на 1500 фразах, — но перевод пишет
  ///   человек, и первая же добавленная тема может их создать.
  /// * **Шаблон центра, который кандидат заполняет.** «Ich brauche ...» в
  ///   центре и «Ich brauche Hilfe.» кандидатом: многоточие это место под
  ///   своё слово, «Hilfe» его заполняет, и игрок, ткнувший в перевод
  ///   заполненной фразы, прав ровно так же. Шаблонов в корпусе сейчас ноль;
  ///   в прежней тысяче фраз их было 239, а пар с заполнением — 68 на
  ///   немецком и 72 на украинском, и они самые похожие из всех: без этого
  ///   правила вставали бы в круг первыми. Правило и написано для того
  ///   корпуса, а живёт в этом как ограждение.
  ///
  /// **Направленно, и это главное.** Проверяется, что описывает центр, а не
  /// то, что похожи два текста. Обратное направление — центр конкретен, а
  /// кандидат шаблон — двусмысленности не создаёт: на вопрос «Ich brauche
  /// Hilfe.» перевод с незаполненной дырой не отвечает, и такой вариант самый
  /// трудный законный, а не второй верный. Здесь стоял симметричный
  /// `isSameAnswerAs`, и он выбрасывал из круга как раз эти — законные —
  /// варианты, а двусмысленные оставлял, потому что считался на языке
  /// вариантов вместо языка центра.
  ///
  /// По нынешнему корпусу центр не описывает чужую фразу **ни разу**: ни на
  /// немецком, ни на украинском, ни одной пары на 1500 фразах. В прежней
  /// тысяче таких центров было 13 на немецком и 14 на украинском, и до
  /// дюжины самых похожих такой кандидат доходил у 4 и 5 соответственно.
  /// Почему проверка остаётся при нулевом счёте — в [QuestionBuilder].
  bool describes(ShownPhrase other) => key == other.key || _covers(other);

  /// Заполняется ли этот шаблон текстом [other]: слова шаблона идут в [other]
  /// в том же порядке, а дыры принимают что угодно.
  bool _covers(ShownPhrase other) {
    if (!hasHole) return false;

    final parts = [
      for (final segment in segments)
        if (segment.isNotEmpty) segment,
    ];
    // Шаблон из одного многоточия заполнялся бы чем угодно и вымел бы из
    // круга весь пул. Такой фразы в корпусе нет, и появиться она может только
    // ошибкой контента — но обвалить на ней сборку круга значило бы наказать
    // игрока за чужую опечатку.
    if (parts.isEmpty) return false;

    final text = other.words;
    var at = 0;
    for (var i = 0; i < parts.length; i++) {
      final part = parts[i];
      // Отрезок в начале строки обязан стоять в начале: «Wo ist ...?» — это
      // не любая фраза со словами «wo ist», а фраза, которая с них
      // начинается.
      final anchored = i == 0 && segments.first.isNotEmpty;
      final found = anchored
          ? (_matchesAt(text, part, at) ? at : -1)
          : _indexOf(text, part, at);
      if (found < 0) return false;
      at = found + part.length;
    }
    // Отрезок в конце строки обязан стоять в конце — по той же причине.
    return segments.last.isEmpty || at == text.length;
  }

  static bool _matchesAt(List<String> text, List<String> part, int at) {
    if (at + part.length > text.length) return false;
    for (var i = 0; i < part.length; i++) {
      if (text[at + i] != part[i]) return false;
    }
    return true;
  }

  static int _indexOf(List<String> text, List<String> part, int from) {
    for (var at = from; at + part.length <= text.length; at++) {
      if (_matchesAt(text, part, at)) return at;
    }
    return -1;
  }

  /// Место под своё слово: три точки подряд. Одиночный символ «…» ловится тем
  /// же выражением, потому что редактор контента подставляет его сам.
  ///
  /// В нынешнем корпусе не встречается ни разу, и выражение оставлено
  /// нарочно: им набирались 239 шаблонов прежней тысячи, форма законна и
  /// вернётся с первой же правкой листа. Стоит оно одного `split` на фразу
  /// при чтении корпуса — один раз за жизнь сборщика; снять его значило бы
  /// вернуть круг с двумя верными ответами в тот день, когда многоточие
  /// появится снова.
  static final RegExp _holes = RegExp(r'\.{3,}|…');

  /// Всё, что не буква и не цифра, разделяет слова. Класс задан через
  /// `\p{L}`, а не `\w`: `\w` в Dart — это латиница с подчёркиванием, и
  /// «heiße» разорвалось бы на «hei» и «e», а украинское слово исчезло бы
  /// целиком.
  static final RegExp _notWord = RegExp(r"[^\p{L}\p{N}'’\-]+", unicode: true);

  /// Апостроф и дефис по краям слова — это знак, а не буква: «— так» и
  /// «слово-» не должны отличаться от «так» и «слово».
  static final RegExp _edges = RegExp(r"^['’\-]+|['’\-]+$");
}
