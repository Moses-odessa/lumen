/// Правило показа имени созвездия: **язык интерфейса → язык подсказок →
/// slug**.
///
/// Правило живёт отдельным классом, а не выражением `a[slug] ?? b[slug] ??
/// slug` на месте подписи, ровно по одной причине: откат должен быть **явным**
/// и одним. Написанное на месте, оно оказалось бы написано трижды — карта,
/// экран прогресса, ритуал, — и в третий раз без последнего звена. Подпись
/// созвездия без имени — пустое место на небе: игрок видит звёзды, к которым
/// не приписано ничего, и это выглядит поломкой отрисовки, а не отсутствием
/// перевода.
///
/// Почему порядок такой:
///
/// * **язык интерфейса первым** — игрок читает приложение на выбранном языке,
///   и подпись темы обязана попадать в тот же язык, что и всё вокруг неё;
/// * **язык подсказок вторым** — имён всего пять языков, а интерфейсов шесть:
///   французского контента нет вовсе. Француз, который учит немецкий с
///   английскими подсказками, увидит английское имя — язык, который он в игре
///   уже читает, а не латинский slug;
/// * **slug третьим** — на случай темы, которой имя ещё не написали. Показать
///   `first_contact` некрасиво, но это не падение и не пустая подпись; а
///   валидатор контента такую тему в запущенный ярус не пустит.
///
/// Обе карты приходят из `ContentDatabase.constellationNamesFor`, по одной на
/// язык. Карты могут совпасть — у немца, который учит немецкий, или когда
/// подсказки и интерфейс на одном языке; это не особый случай: вторая попытка
/// просто повторит первую.
library;

/// Имена созвездий, готовые к подписи, с явным откатом по языкам.
class ConstellationNaming {
  const ConstellationNaming({
    required this.interfaceNames,
    required this.nativeNames,
  });

  /// Пустое именование: всё покажется слагами.
  ///
  /// Нужно не для тестов, а для кадра до того, как база ответила. Иначе
  /// вызывающему пришлось бы держать `ConstellationNaming?` и решать про
  /// откат второй раз — то есть ровно то, от чего этот класс избавляет.
  const ConstellationNaming.slugsOnly()
      : interfaceNames = const {},
        nativeNames = const {};

  /// Имена на языке интерфейса — том, на котором игрок читает приложение.
  final Map<String, String> interfaceNames;

  /// Имена на языке подсказок — том, на котором игрок видит переводы фраз.
  final Map<String, String> nativeNames;

  /// Имя темы для показа. Никогда не пустое и никогда не `null`.
  String nameOf(String constellation) =>
      _named(interfaceNames, constellation) ??
      _named(nativeNames, constellation) ??
      constellation;

  /// Пустая строка — это **отсутствие** имени, а не имя.
  ///
  /// Проверка не лишняя и не оборонительная: валидатор запрещает пустое имя в
  /// исходниках, но между исходником и подписью лежат YAML, сборка и ассет из
  /// предыдущего релиза. Стоит она одного `trim` на тему, а без неё
  /// единственный пробел в языковом файле съедал бы подпись молча — и откат
  /// на язык подсказок не сработал бы, потому что ключ-то есть.
  static String? _named(Map<String, String> names, String constellation) {
    final name = names[constellation];
    if (name == null || name.trim().isEmpty) return null;
    return name;
  }
}
