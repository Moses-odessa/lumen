/// Код языка проекта → тег локали для синтеза речи.
///
/// Проект хранит язык двумя буквами (`de`, `en`), а синтезу нужен BCP-47 с
/// регионом. Без региона Android выбирает вариант сам, и «en» может
/// оказаться индийским английским, а «de» — швейцарским; для образца
/// произношения это не мелочь.
library;

/// Регион по умолчанию для каждого языка изучения.
///
/// Выбран тот, на который написан контент: немецкий — германский стандарт
/// (`content/lang/de.yaml` вычитан по Duden), английский — американский как
/// самый распространённый в системных голосах.
const Map<String, String> _localeByLang = {
  'de': 'de-DE',
  'en': 'en-US',
  'ru': 'ru-RU',
  'uk': 'uk-UA',
};

/// Тег локали для языка. Неизвестный язык отдаётся как есть: пусть движок
/// решает сам, это лучше, чем молчать.
String speechLocaleFor(String lang) => _localeByLang[lang] ?? lang;

/// Человеческое название языка — для экрана «голос не установлен».
const Map<String, String> speechLanguageNames = {
  'de': 'немецкий',
  'en': 'английский',
  'ru': 'русский',
  'uk': 'украинский',
};
