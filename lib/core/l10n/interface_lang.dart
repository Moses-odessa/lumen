/// Язык, на котором игрок читает приложение, — и имена созвездий, которые из
/// него следуют.
///
/// Оба провайдера здесь ради одного: вопрос «на каком языке эта подпись»
/// должен решаться в **одном** месте. Имена созвездий показываются в трёх
/// (подпись на небе, строка яркости в профиле, текст напоминания), и три
/// независимых ответа разошлись бы — тихо и по-разному.
///
/// Файл лежит в `core/l10n`, а не рядом с `constellationNamesProvider` в слое
/// данных, по причине, записанной там же: сборке нужен язык интерфейса, а он
/// — `supportedLocales` и разрешение локалей, то есть l10n. `lib/data` не
/// импортирует `lib/core` нигде, и начинать это с имён созвездий незачем.
library;

import 'package:flutter/foundation.dart';
import 'package:flutter/widgets.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import '../../data/content/constellation_naming.dart';
import '../../data/content/content_provider.dart';
import '../../data/repositories/player_repository.dart';
import 'app_localizations.dart';

/// Язык интерфейса: настройка игрока, а если её нет — язык системы.
///
/// У вопроса два источника: `Player.uiLang` (отдельная настройка от родного
/// языка — можно учить немецкий с украинского, а интерфейс держать
/// английским) и локали системы, сведённые к
/// [AppLocalizations.supportedLocales]. Сводить их — работа Flutter, и здесь
/// она не пишется заново: вызывается **та же** функция
/// [basicLocaleListResolution] с теми же аргументами, что `Localizations`
/// внутри `MaterialApp` (задана локаль — `[locale]`, не задана —
/// `platformDispatcher.locales`). Своё «а если не задана» рядом с готовым
/// разрешением означало бы два правила выбора языка: интерфейс по одному,
/// подпись созвездия по другому. Разошлись бы они молча и не сразу — пока
/// настройка задана явно, оба ответа одинаковы, — а расходиться начали бы
/// там, где язык интерфейса решает не игрок, а система.
///
/// Заодно это чинит случай, который своим `??` не покрылся бы: код языка,
/// которого в `supportedLocales` нет. `MaterialApp` в таком случае берёт
/// первый поддерживаемый, и подпись обязана поехать за ним, а не остаться на
/// языке, которого игрок не видит.
///
/// Локали системы читаются через биндинг, а не через
/// `PlatformDispatcher.instance`, по двум причинам: это ровно тот источник,
/// который читает `Localizations`, и в тестах биндинг подменяем — иначе
/// ветку «интерфейс по системе» проверить нечем.
///
/// Смену языка телефона на живом приложении провайдер сам не заметит:
/// `Provider` пересчитывается по зависимостям, а не по сигналам платформы.
/// Сбрасывает его `LumenApp` по `didChangeLocales` — там и написано, что
/// будет без этого.
///
/// Зависимость — одно поле игрока, а не игрок целиком. У [Player] нет
/// значимого равенства, поэтому **любая** запись — тумблер звука, смена
/// яруса, орбита и час игры в конце каждого ритуала — считается сменой
/// зависимости. Здесь это стоило только лишнего пересчёта (строка на выходе
/// та же, и слушателям Riverpod ничего не сообщал), а у именования строкой
/// ниже из того же места получался индикатор загрузки. Правило одно на оба
/// провайдера, поэтому и написано оно одинаково.
final interfaceLangProvider = Provider<String>((ref) {
  final chosen = ref.watch(playerControllerProvider.select((p) => p?.uiLang));
  return basicLocaleListResolution(
    chosen == null
        ? WidgetsBinding.instance.platformDispatcher.locales
        : [Locale(chosen)],
    AppLocalizations.supportedLocales,
  ).languageCode;
});

/// Имена созвездий для нынешнего игрока — единственная сборка в проекте.
///
/// Правило показа (язык интерфейса → язык подсказок → slug) живёт в
/// [ConstellationNaming] и здесь не повторяется: провайдер только приносит
/// ему две карты имён. Язык подсказок — `Player.nativeLang`, язык интерфейса
/// — [interfaceLangProvider] строкой выше; ближе, чем в одном файле, эти два
/// решения свести нельзя.
///
/// **Отказ базы имён — это отсутствие имён, а не ошибка.** Пустая
/// [ConstellationNaming.slugsOnly] вместо исключения выбрана не из
/// вежливости: ассет старой сборки, в котором нет таблицы имён, иначе уронил
/// бы небо целиком. Экран ждёт этот future, чтобы не показать подписи слагами
/// и тут же переписать их именами (абзац ниже), — и ошибка оставила бы игрока
/// на индикаторе загрузки навсегда. Латинские слаги на карте — третье звено
/// того же отката, и битую сборку они выдают заметнее, чем пустой экран.
///
/// Из этого следуют две вещи, которые тут легко потерять.
///
/// Первая: `catch` держит и обе `ref.watch`, а не только запросы. Провайдер
/// обязан быть **неспособным** ответить ошибкой, потому что у обоих экранов
/// ветка «ни данных, ни ошибки» — тот же индикатор загрузки; ошибка
/// именования, откуда бы она ни пришла, означала бы вечное ожидание. Экраны
/// на это обещание всё же не опираются (у них любая ошибка ведёт в одну
/// ветку) — но обещание дано здесь, и здесь же оно выполняется.
///
/// Вторая: откат обязан быть **быстрым**, иначе он не откат. Riverpod
/// перезапускает упавший провайдер сам, и пока идут попытки, его `future` не
/// завершается — то есть `await` ниже висел бы все сорок секунд повторов, а
/// экраны эти сорок секунд держали бы индикатор. Поэтому у
/// `constellationNamesProvider` повторы выключены; причина записана там.
///
/// Про кадр до ответа базы. Имена приходят асинхронно, а карта рисуется
/// сразу, поэтому у экрана два честных варианта: показать слаги и заменить их
/// именами или подождать. Выбран второй: подписи, меняющиеся у игрока на
/// глазах, читаются как поломка, а слаг — всего лишь как непереведённая тема.
/// Ждать здесь дёшево ровно потому, что небо и так ждёт **эту же** базу
/// (`phrasesUpTo`), а запрос имён — двести пятьдесят коротких рядов; экран
/// неба ждёт оба future одним ожиданием, и первый же кадр карты подписан
/// именами. Кадр со слагами существует для тех мест, которые ждать не могут:
/// у [ConstellationNaming.slugsOnly] на это своя докстрока.
final constellationNamingProvider =
    FutureProvider<ConstellationNaming>((ref) async {
  try {
    final interfaceLang = ref.watch(interfaceLangProvider);
    // Язык подсказок — одно поле, а не игрок целиком, и по той же причине,
    // что у `interfaceLangProvider`: у `Player` нет значимого равенства.
    // Здесь эта разница видна игроку. Провайдер асинхронный, и смена
    // зависимости переводит его в `AsyncLoading` не-seamless, а оба экрана
    // сопоставляют только `AsyncData` — то есть запись орбиты в конце ритуала
    // роняла подпись в индикатор загрузки. Кадр почти никогда не успевал
    // нарисоваться, потому что запрос уже в кеше и завершается за
    // микрозадачу, — но это совпадение, а не код: у некешированного языка
    // (смена языка подсказок) или на серии повторов оно не держится.
    final nativeLang =
        ref.watch(playerControllerProvider.select((p) => p?.nativeLang)) ??
            defaultNativeLang;

    // Два запроса, а не один с `IN`: когда язык интерфейса и язык подсказок
    // совпали (украинец с украинским интерфейсом — обычный случай), family с
    // одинаковым аргументом отдаёт одно состояние, то есть один запрос. Это
    // видно здесь, а не спрятано в SQL.
    return ConstellationNaming(
      interfaceNames:
          await ref.watch(constellationNamesProvider(interfaceLang).future),
      nativeNames:
          await ref.watch(constellationNamesProvider(nativeLang).future),
    );
  } catch (e) {
    if (kDebugMode) debugPrint('[naming] имена созвездий не прочитались: $e');
    return const ConstellationNaming.slugsOnly();
  }
});
